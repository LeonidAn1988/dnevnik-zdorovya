export type Measurement = BpReading | GlucoseReading

export const isBp = (m: Measurement): m is BpReading => m.kind === 'bp'
export const isGlucose = (m: Measurement): m is GlucoseReading => m.kind === 'glucose'

/**
 * Ритм приёма. Пусто или бессмысленно — принимать каждый день.
 *
 * Поля плоские, а не размеченное объединение: объект уходит в резервную копию
 * и приходит из копии чужой версии, где размётки может не быть вовсе. Правило
 * выбирается по наличию значений, и `weekdays` старше цикла — если по недосмотру
 * заполнено и то и другое, дни недели понятнее человеку.
 */
export interface Rhythm {
  /** Дни недели: 1 — понедельник, 7 — воскресенье. Пустой список — правила нет. */
  weekdays?: number[]
  /** Цикл: сколько дней подряд принимать. */
  onDays?: number
  /** Цикл: сколько дней перерыва. Ноль — перерыва нет, то есть каждый день. */
  offDays?: number
  /**
   * День, с которого отсчитывается цикл.
   *
   * Без него «через день» встаёт на ту половину, которую выберет случай, и
   * ошибку замечают через неделю, когда связать её уже не с чем.
   */
  from?: number
}

/**
 * Коробка в доме — вещь, а не назначение.
 *
 * Что это, сколько осталось, до какого числа годно. Кто это принимает, когда и
 * по сколько — в `Regimen`: одну коробку могут пить двое, а кончившийся курс не
 * значит, что коробку пора выбросить.
 */
export interface Medicine {
  id: string
  /** Название с упаковки. */
  name: string
  /** Дозировка как написано на коробке: «5 мг», «10 мг/мл». Свободный текст: вариантов слишком много. */
  dose: string
  /**
   * Лекарственная форма: таблетки, капсулы, капли глазные.
   *
   * Подставляется из реестра. Отдельно от дозировки, потому что одна и та же
   * цифра у разных форм значит разное: «5 %» у геля и «5 мг» у таблеток.
   */
  form?: string
  /**
   * Международное непатентованное наименование. Подставляется из реестра.
   * Нужно там, где врач называет препарат одним словом, а на упаковке
   * напечатано торговое название другой фирмы.
   */
  inn?: string
  /** Остаток в таблетках, ампулах, дозах. `null` — не считаем этот препарат. */
  left: number | null
  /** Срок годности. `null` — не указан. */
  expires: number | null
  note?: string

  /**
   * Что это по документам: 1 — БАД, 2 — гомеопатия. Пусто — обычное лекарство.
   *
   * Подставляется из справочника и показывается рядом с названием. БАД не
   * лекарство и лечебного действия не заявляет, гомеопатия зарегистрирована
   * лекарством, но действующего вещества в проверяемом количестве не содержит.
   * Человек вправе видеть это в своём же списке — тем более когда несёт его
   * врачу.
   */
  kind?: 1 | 2

  /** Производитель или держатель регистрационного удостоверения. Из реестра. */
  maker?: string
  /**
   * Сколько единиц в упаковке — в тех единицах, какие у этой формы выпуска.
   *
   * У таблеток штуки, у капель и сиропа миллилитры, у спрея дозы. Какие
   * именно — знает `unitsOf`. Нужно кнопке «Купил упаковку» и списку покупок.
   */
  packSize?: number

  /**
   * Сколько капель в миллилитре. Только у капель, иначе бессмысленно.
   *
   * Пусто — считаем по фармакопее, двадцать. Число здесь потому, что оно
   * зависит от препарата: у масляных растворов капля мельче, и настоящее
   * значение печатают в инструкции.
   */
  dropsPerMl?: number
  /**
   * Для чего его держат: «Давление», «Простуда», «Перевязка».
   *
   * Свободная строка, а не ключ из списка: справочника полок в шкафу не
   * существует, люди называют их своими словами, и смена набора подсказок не
   * должна требовать переноса данных.
   *
   * Не `category`: это имя уже занято категорией давления (`classify.ts`), и
   * два разных «category» в одном дневнике рано или поздно перепутались бы.
   *
   * Пусто — и это обычное состояние: подсказка предлагается при заведении, а в
   * уже заведённые коробки не проставляется молча.
   */
  purpose?: string

  /** Номер регистрационного удостоверения — по нему ищется официальная инструкция. */
  regNumber?: string

  /**
   * Когда остаток подтверждали последний раз.
   *
   * Без этого «хватит на 28 дней» устаревало со второго дня: остаток менялся
   * только вручную, а предупреждение «пора заказывать» не срабатывало никогда.
   */
  leftAt?: number
  /**
   * Отпускается по рецепту.
   *
   * Меняет срок, за который надо спохватиться: за неделю к врачу не успеть, а
   * у льготников это ещё и отдельный визит за выпиской. Подставляется из
   * справочника и правится руками — реестр говорит про форму выпуска, а не
   * про конкретную пачку.
   */
  rx?: boolean

  /** Когда коробку последний раз меняли. Ставится хранилищем, см. `Measurement.updatedAt`. */
  updatedAt?: number
}

/**
 * Курс приёма: кто принимает из этой коробки, когда и до какого дня.
 *
 * Отдельно от коробки, потому что это разные вещи с разной судьбой. Коробка
 * стоит в шкафу и принадлежит дому; курс принадлежит человеку и кончается.
 * Пока они были одним, аптечка не могла быть общей, одну упаковку не могли
 * принимать двое, а «курс кончился» было не отличить от «коробка не нужна».
 *
 * Своих полей про саму коробку здесь нет намеренно: название, остаток и срок
 * годности спрашиваются у неё, иначе они разойдутся.
 */
export interface Regimen {
  id: string
  /** Из какой коробки принимают — `Medicine.id`. */
  medicineId: string
  /**
   * Кто принимает — идентификатор человека из `Settings.people`.
   *
   * В отличие от прежнего `Medicine.owner`, пустым не бывает: курс без человека
   * бессмыслен, а коробка человека больше не требует.
   */
  person: string

  /**
   * Последний день курса — местная полночь.
   *
   * Отдельным полем, а не последним этапом схемы: врач говорит «курс десять
   * дней», а не «этап на десять дней». Пусто — курс без конца, как у давления.
   *
   * После этого дня напоминания молчат и расход считается нулевым — иначе
   * законченный курс продолжал бы звать принять отменённое и держал коробку в
   * списке покупок вечно.
   */
  endsAt?: number


  /**
   * Время приёмов: «08:00», «20:00». Пусто — препарат по потребности,
   * напоминать не о чем и в расписание он не идёт.
   */
  times?: string[]
  /** Сколько штук за один приём. По умолчанию одна. */
  perTime?: number
  /** Когда принимать относительно еды. Влияет только на подпись напоминания. */
  meal?: 'before' | 'after' | 'any'

  /**
   * В какие дни принимать. Пусто — каждый день, как было всегда.
   *
   * Времена приёма и дни приёма — разные вопросы: «по таблетке утром и вечером»
   * отвечает на первый, «через день» на второй. Держать их в одном поле не
   * вышло бы: у времён нет календаря, а у дней нет часов.
   */
  rhythm?: Rhythm
  /**
   * Схема с меняющейся дозой. Пусто — доза одна и та же, как было всегда.
   * Этапы идут подряд, начиная с `planFrom`.
   */
  plan?: DoseStage[]
  /** С какого дня считается первый этап схемы. */
  planFrom?: number
  /** Сколько уходит в сутки. Нужно ровно для одного — предсказать, на сколько дней хватит. */
  perDay?: number | null

  /**
   * Списывать остаток по расписанию, не дожидаясь подтверждения.
   *
   * Нажимать «Принял» трижды в день согласится не всякий, а несписанный
   * остаток врёт и предупреждение о том, что пора покупать, не приходит.
   * Здесь приложение считает, что назначенное принято, и говорит об этом
   * прямо. Отметки приёма при этом остаток не трогают — иначе списалось бы
   * дважды.
   */
  autoDeduct?: boolean

  /**
   * С какого дня препарат ведётся в дневнике.
   *
   * Без этого расписание распространялось на всё прошлое: препарат, добавленный
   * сегодня, показывал пропуски за два месяца назад — ровно на всю глубину
   * хранения отметок. Человек, впервые заполнивший аптечку, видел полосу
   * сплошных провалов и решал, что приложение его укоряет.
   *
   * Пусто — препарат заведён до появления этого поля; тогда началом считается
   * первая отметка о приёме, а если отметок нет — сегодняшний день.
   */
  since?: number

  /**
   * С какого месяца человек принимает препарат — по его собственным словам.
   *
   * Отдельно от `since`: тот про дневник, а этот про жизнь. До приложения
   * препарат могли пить годами, и на вопрос врача «как давно принимаете»
   * дневник отвечать не умел — он знал только, когда завели карточку.
   *
   * Точность месяца намеренная: день начала приёма человек не помнит, а
   * спрашивать то, чего не помнят, — верный способ получить выдуманное число.
   */
  startedAt?: number

  /**
   * Отметки о принятых дозах. Хранится только недавнее — по этим меткам видно,
   * принято ли сегодня, а история приёма за годы никому не нужна и раздувает
   * резервную копию.
   */
  taken?: number[]

  /**
   * Снятые отметки — надгробия для `taken`.
   *
   * Отметки складываются при обмене с другими телефонами семьи: у каждого свой
   * список, и слияние берёт объединение. Снятая отметка в списке просто
   * отсутствует — и приходит обратно с чужого телефона, где её ещё не сняли.
   * «Отметил не ту таблетку, снял» держалось до следующего чтения чужого
   * файла, а потом отменялось само.
   *
   * Поэтому снятие оставляет след, а слияние вычитает следы из объединения.
   * Хранится столько же, сколько и сами отметки: свёртка истории чистит оба
   * списка одной меркой.
   */
  untaken?: number[]

  /**
   * Свёрнутая история приёма по месяцам: `'2026-07' → { назначено, принято }`.
   *
   * Отметки живут `KEEP_INTAKES_DAYS` дней и дальше выбрасываются — иначе за
   * годы их набирается несколько тысяч на препарат, и резервная копия пухнет.
   * Но врач спрашивает «сколько пропускаете» не за два месяца, а за всё время
   * лечения, и выбрасывать ответ на этот вопрос нельзя.
   *
   * Свёртка решает оба: месяц весит две цифры вместо сотни отметок, а на вопрос
   * врача отвечает. Точность до месяца намеренная — «пропустил 4 приёма в июле»
   * это то, что произносят вслух, а какие именно четыре, не спрашивает никто.
   */
  history?: Record<string, { planned: number; taken: number }>

  /**
   * До какого дня история уже свёрнута.
   *
   * Без этой отметки повторная свёртка считала бы одни и те же дни заново:
   * граница в шестьдесят дней сдвигается каждый день, и месяц уходит за неё по
   * кусочку. Здесь — где именно остановились в прошлый раз.
   */
  foldedUntil?: number
  /** Когда курс последний раз меняли. Ставится хранилищем, см. `Measurement.updatedAt`. */
  updatedAt?: number
}

/** Часы стандартных приёмов: кнопки в форме препарата. */
export interface IntakeTimes {
  morning: string
  day: string
  evening: string
  night: string
}

/**
 * Этап схемы приёма: по сколько принимать и сколько дней.
 *
 * Врач редко назначает одну дозу навсегда. Её наращивают неделями — «первую
 * неделю по половине, потом по целой» — и так же снижают при отмене. До сих пор
 * у коробки было одно число `perTime` на всё время, и такое назначение
 * приходилось держать в голове или переписывать вручную каждую неделю. Ровно
 * там, где ошибка стоит дороже всего.
 */
export interface DoseStage {
  /** Штук за один приём. `0.5` — половина таблетки, `0` — перерыв. */
  perTime: number
  /**
   * Сколько дней длится этап. `null` у последнего этапа означает «дальше так
   * же»: схема наращивания заканчивается поддерживающей дозой и продолжается.
   * Число у последнего этапа значит, что курс на этом кончается.
   */
  days: number | null
}

/**
 * Кнопка стандартного приёма в форме препарата: «Утром», «В обед», «Перед сном».
 *
 * Пришла на смену четырём жёстким временам. Четыре покрывали почти все
 * назначения, но не все: кому-то назначают приём каждые шесть часов, кому-то
 * хватает одного утреннего, и лишние кнопки он пролистывает каждый раз.
 * Заголовок правится вместе со временем — «На ночь» и «Перед сном» это разные
 * слова для одного и того же, и выбирать их человек вправе сам.
 */
export interface IntakeSlot {
  /** Устойчивый ключ. У первых четырёх — прежние `morning`…`night`. */
  id: string
  title: string
  /** «08:00». */
  time: string
}

/**
 * Расписание измерений давления.
 *
 * Одно понятие на две задачи. Без срока (`days: null`) — просто «напоминай
 * мерить»: телефон умеет напомнить про таблетку и не умеет про тонометр. Со
 * сроком — курс, назначенный врачом: «две недели утром и вечером».
 *
 * Схему вводит человек со слов врача. Приложение режимов не предлагает и
 * предлагать не должно: предложить режим измерений значит назначить.
 */
export interface MeasurePlan {
  /** Когда мерить: «08:00», «20:00». Пусто — не напоминать. */
  times: string[]
  /** Сколько дней. `null` — бессрочно: ни счётчика, ни строки в отчёте. */
  days: number | null
  /** Местная полночь первого дня. У бессрочного — день, когда завели. */
  from: number
}

/** Оформление. «Как в системе» — значение по умолчанию, оно же поведение до этой настройки. */
export type ThemeChoice = 'auto' | 'light' | 'dark'

/** Размер текста: от «мельче» до «очень крупно». */
export type TextScale = 'small' | 'normal' | 'large' | 'xlarge'

/** Плотность вёрстки: насколько тесно стоят блоки. */
export type Density = 'compact' | 'normal' | 'roomy'

/**
 * Разделы нижней навигации.
 *
 * Отец ведёт все три дневника, сыну нужны только лекарства. Состав панели —
 * личная настройка: он меняется прямым действием и никогда сам по себе.
 * Появляющиеся и исчезающие вкладки сбивают с толку сильнее, чем лишний пункт.
 */
export interface SectionVisibility {
  /**
   * Обзор собран из сводок давления и сахара. Если оба дневника скрыты, он
   * пуст, и держать его силой незачем — поэтому скрывается наравне с прочими.
   * Единственное ограничение: хотя бы один раздел обязан остаться, иначе от
   * приложения не остаётся ничего.
   */
  overview: boolean
  bp: boolean
  glucose: boolean
  intake: boolean
  cabinet: boolean
}

/** Ключи разделов приложения. Настройки, прибор и отчёт живут в шапке и не скрываются. */
export type SectionKey = keyof SectionVisibility

export interface Settings {
  /** Ключ сопряжения, 32 hex-символа. */
  pairingKey: string
  /** Как подписаны пользователи прибора. */
  userNames: Record<number, string>
  /** Активный пользователь, чьи данные показываем. */
  activeUser: number

  /**
   * Люди, чьи дела ведутся в этом дневнике.
   *
   * Не то же самое, что пользователи прибора. Тонометр помнит ровно двух — это
   * железо, две кнопки на корпусе. Людей в семье может быть четверо, а у
   * ребёнка тонометра нет вовсе, и лекарства у него всё равно есть. Слитые в
   * одно, эти понятия упирались в потолок из двух человек там, где потолка нет.
   *
   * Список живёт в настройках, а не отдельным хранилищем: это несколько имён,
   * они переносятся вместе с настройками и восстанавливаются вместе с ними.
   */
  people: Person[]

  /** Чьи дела показываем. Идентификатор из `people`. */
  activePerson: string

  /**
   * Кого с кем объединили: прежний идентификатор человека → выживший.
   *
   * Надгробия для человека нет и не заводится намеренно: надгробие умеет одно —
   * не пускать обратно, — а здесь нужно второе. На других телефонах семьи
   * мёртвый идентификатор остаётся, и записи будут приходить с ним вечно.
   * Такая запись невидима у всех: поиск по человеку сравнивает только с
   * выбранным, а запасной путь «по кнопке прибора» работает лишь когда поля
   * `person` нет вовсе. Карта их перецепляет.
   *
   * Цепочки схлопываются при записи: если A уже вёл к B, а B объединили с C,
   * то A ведёт к C, а не к мёртвому B.
   */
  mergedPeople?: Record<string, string>

  /** Целевое давление, назначенное врачом. */
  targetSys: number
  targetDia: number

  /** Верхняя граница нормы натощак и до еды, ммоль/л. */
  glucoseFastingMax: number
  /** Верхняя граница нормы через 2 часа после еды, ммоль/л. */
  glucosePostMealMax: number
  /** Порог гипогликемии, ммоль/л. */
  glucoseLow: number

  /** Показывать ли раздел сахара. Включается сам, как только появляется первая запись. */
  trackGlucose: boolean

  /** Светлая или тёмная тема. */
  theme: ThemeChoice

  /**
   * Размер текста во всём приложении.
   *
   * Не только ради пожилых. Дневником пользуются и те, кому шрифт по
   * умолчанию крупен: на маленьком экране лишние два пункта съедают строку
   * таблицы и заставляют листать там, где всё умещалось. Системная настройка
   * Android до WebView не доходит, поэтому решать приходится здесь.
   */
  textScale: TextScale

  /**
   * Плотность вёрстки: отступы между блоками.
   *
   * Отдельно от размера текста, потому что запросы разные. «Плохо вижу» — это
   * крупнее буквы; «не хочу листать» — это теснее отступы. Смешивать их в одну
   * ручку значит не дать ни того, ни другого.
   */
  density: Density

  /** Какие разделы показывать в нижней навигации. */
  sections: SectionVisibility
  /** С какого экрана открывается приложение. */
  startTab: string

  /**
   * Напоминать ли о приёме системными уведомлениями.
   *
   * Выключено по умолчанию: уведомления требуют разрешения, и включать их за
   * человека нельзя. Кроме того, в вебе их не существует вовсе — там
   * расписание по-прежнему уезжает в календарь телефона.
   */
  remindersOn: boolean
  /** Мелодия напоминания. Идентификатор из списка платформы. */
  reminderSound: string
  /**
   * Повторять напоминание, пока приём не отмечен.
   *
   * Включено по умолчанию: пропущенная таблетка дороже лишнего уведомления.
   * Повторов конечное число — бесконечный трезвон люди отключают целиком, и
   * тогда не работает ничего.
   */
  remindersRepeat: boolean
  /**
   * Напоминать ли измерить давление.
   *
   * Настройка устройства, а не человека — рядом с `remindersOn`, и из чужой
   * копии не берётся. Независима от напоминаний о приёме: курс измерений
   * бывает у того, кто таблеток не пьёт вовсе.
   */
  measureRemindOn: boolean

  /**
   * Часы стандартных приёмов — кнопки в форме препарата.
   *
   * Раньше были зашиты в код: 08:00, 13:00, 19:00, 22:00. Человеку, у которого
   * утро в шесть, а вечер в семнадцать, они не подходили — и он вводил время
   * руками для каждого препарата. Теперь настраиваются один раз.
   */
  intakeTimes: IntakeTimes
  /**
   * Кнопки стандартных приёмов. Пусто — берутся четыре из `intakeTimes`, как
   * было раньше: дневник, заведённый до появления поля, ничего не теряет.
   */
  intakeSlots?: IntakeSlot[]
  /** Общее расписание измерений: одиночке и как запасное для семьи. */
  measurePlan?: MeasurePlan

  /**
   * Знакомство при первом запуске пройдено или пропущено.
   *
   * Показывается один раз и только на пустом дневнике: тому, кто обновился с
   * записями, знакомиться уже не с чем.
   */
  onboarded: boolean

  /**
   * Приглашение пройти курс по приложению уже показывали.
   *
   * Отдельно от `onboarded`: курс нужен и тем, кто обновился с полным
   * дневником, — раньше его просто не было. Показываем один раз и больше не
   * возвращаемся, даже если человек его закрыл: навязываться нельзя, а найти
   * курс потом можно в настройках.
   */
  guideOffered?: boolean

  /**
   * До какого момента развёрнутые предупреждения спрятаны.
   *
   * Предупреждение, которое висит, пока причина не устранена, надёжно доносит
   * ровно один раз. Дальше его перестают читать — и в тот день, когда оно
   * окажется важным, не заметят. Поэтому после «Понятно» баннер уходит на
   * неделю, а сигнал остаётся точкой на нужной кнопке: тихо, но не молча.
   */
  nudgesUntil: { backup: number; cabinet: number }

  /**
   * Шифровать ли копию паролем.
   *
   * Выключено по умолчанию: файл и так лежит за аккаунтом облака или в памяти
   * телефона, то есть один рубеж уже есть. Второй пароль, который надо помнить
   * годами, у пожилого человека означает потерю всего дневника без единого
   * шанса на восстановление — ключ не хранится нигде, и подобрать его нечем.
   * Поэтому включается сознательно и с прямым предупреждением.
   *
   * Сам пароль здесь не хранится и храниться не будет: копия, в которой лежит
   * пароль от неё же, не защищена ничем.
   */
  backupEncrypt: boolean

  /** Когда сделана последняя резервная копия. null — не делалась. */
  backupLastAt: number | null
  /** Сколько записей вошло в последнюю копию: по расхождению видно, что она устарела. */
  backupLastCount: number
  /**
   * Слепок содержимого дневника на момент последней копии.
   *
   * По числу записей видно не всё: отметка приёма, правка остатка и смена дозы
   * его не меняют, и файл оставался вчерашним. Для копии это терпимо, для
   * семейного обмена нет — жена поправит остаток, а муж не увидит.
   */
  backupLastSignature?: string

  /**
   * Аптеки, в которых человек ищет лекарства.
   *
   * Список сетей, а не адресов: ссылки собирает приложение. Пусто — ни одна не
   * выбрана, и кнопка ведёт в поисковик, как было раньше.
   */
  pharmacies?: string[]
}

/**
 * Человек, чьи дела ведутся в дневнике.
 *
 * Появился отдельно от `userNames` намеренно: те подписывают кнопки на приборе,
 * и их всегда две. Человек — это тот, у кого своя аптечка, своё расписание
 * приёма и свой отчёт врачу; связь с памятью прибора у него необязательная.
 */
export interface Person {
  /** Устойчивый идентификатор: имя можно переименовать, ссылки на человека — нет. */
  id: string
  name: string

  /**
   * Свои часы стандартных приёмов: «Утром», «Днём», «Вечером», «На ночь».
   *
   * У каждого они свои по-настоящему: у одного утро в шесть, у другого в
   * девять, и общие на всю семью часы означают, что кому-то придётся вводить
   * время руками для каждого лекарства. Пусто — берутся общие из настроек: так
   * ведут себя все, кто был заведён до появления этой возможности.
   */
  intakeTimes?: IntakeTimes
  /** Свои кнопки приёма. Пусто — общие из настроек. */
  intakeSlots?: IntakeSlot[]
  /** Своё расписание измерений. Пусто — общее из настроек. */
  measurePlan?: MeasurePlan

  /**
   * Своё целевое давление.
   *
   * Врач назначает цель по человеку: жене после родов могут поставить 130/80,
   * а пожилому с давним стажем — 140/90. Общая на всю семью цель означала, что
   * отчёт для врача жены считается по цифрам мужа. Пусто — берётся общая из
   * настроек, как у всех, кто был заведён до появления этой возможности.
   */
  targets?: { sys: number; dia: number }

  /** Свои пороги сахара. Пусто — общие из настроек. */
  glucose?: { fastingMax: number; postMealMax: number; low: number }

  /**
   * Память тонометра, если она у человека есть.
   *
   * Пусто — прибором человек не пользуется: у ребёнка его нет, а взрослых в
   * семье может быть больше двух. Дневник давления у такого человека пустой, и
   * это нормальное состояние, а не поломка.
   */
  deviceUser?: 1 | 2
}

/**
 * След удалённой записи.
 *
 * Удаление, не оставляющее следа, необратимо теряется при любом обмене копиями:
 * запись, стёртая на телефоне, возвращается из файла компьютера, а измерение,
 * убранное руками, приходит обратно при следующей выгрузке с прибора —
 * идентификаторы у записей прибора детерминированные, и он отдаёт всю память
 * целиком каждый раз.
 *
 * Надгробие — это решение человека, а не служебная запись. Поэтому оно
 * переживает и выгрузку, и восстановление из копии, и хранится без срока: весит
 * оно десятки байт, а удаляют в дневнике здоровья редко и осознанно.
 */
export interface Tombstone {
  /** Идентификатор удалённой записи. */
  id: string
  /** Что удалено: измерение, коробка, курс приёма или анализ. Хранилища разные. */
  kind: 'measurement' | 'medicine' | 'regimen' | 'lab'
  /** Когда удалили. Нужно при слиянии, чтобы отличить старое решение от нового. */
  at: number
  /**
   * На какой установке удалили. Пусто — на этой же или до появления поля;
   * при слиянии «неизвестно чьё» считается своим, а не чужим.
   */
  by?: string
}

/**
 * Анализ: что сдают, когда и что получилось.
 *
 * **Черта, за которую этот раздел не заходит.** Приложение хранит числа со слов
 * человека и напоминает сдать — и только. Ни «норма», ни «повышен», ни цвета,
 * ни стрелок, ни референсных интервалов в модели: сравнение результата с нормой
 * и вывод из него — это медицинское изделие, а не дневник (письмо
 * Росздравнадзора 02И-297/20, та же черта записана в `BACKLOG.md` §11).
 * Прецедент рядом: `events.ts` по той же причине не толкует события.
 *
 * Поэтому у анализа есть `unit` — подпись к числу, и `note` — свободная
 * строка, куда человек перепишет что угодно, включая то, что написала
 * лаборатория. Поля «норма» нет и не будет.
 */
export interface LabTest {
  id: string
  /** Как называет его человек: «ТТГ», «Общий анализ крови». */
  name: string
  /** Чей анализ — идентификатор человека из `Settings.people`. */
  owner: string
  /** Когда сдавать. Пусто — анализ без расписания, только записи о сданном. */
  schedule?: LabSchedule
  /** Подпись к числу: «мкМЕ/мл». Не норма и не диапазон. */
  unit?: string
  /** Заметка про сам анализ: «натощак», «в той же лаборатории». */
  note?: string
  results: LabResult[]
  updatedAt?: number
}

/**
 * Когда сдавать.
 *
 * Два способа задать дату, и они не смешиваются: либо своя дата с повтором,
 * либо привязка к концу курса приёма.
 *
 * **Привязка живая, но с заморозкой.** Пока курс существует и у него есть
 * конец, дата пересчитывается от него. Если курс удалили или конец сняли, дата
 * остаётся последней вычисленной, а приложение говорит о разрыве вслух: иначе
 * анализ исчез бы из расписания ровно тогда, когда он нужен.
 */
export interface LabSchedule {
  /** Ближайшая дата сдачи — местная полночь. Считается, а не только хранится. */
  due: number
  /** Повтор раз в столько месяцев. */
  everyMonths?: number
  /** Повтор раз в столько дней — для коротких промежутков. */
  everyDays?: number
  /** Через сколько дней после конца курса приёма. */
  afterRegimen?: string
  afterDays?: number
  /** Во сколько напомнить в день сдачи. Пусто — утром. */
  time?: string
}

/**
 * Один результат.
 *
 * `values` — массив, хотя форма первого выпуска показывает одно число: у общего
 * анализа крови чисел два десятка, и менять формат ради них потом значит ломать
 * уже снятые копии.
 */
export interface LabResult {
  id: string
  /** День сдачи — местная полночь. */
  day: number
  values: number[]
  /** Что написано в бланке своими словами. */
  note?: string
}

/**
 * Снимок бланка анализа.
 *
 * **В резервную копию не идёт и не пойдёт.** Копия — это строка, и она
 * переписывается целиком при каждой отметке приёма: двадцать снимков
 * превратили бы отметку таблетки в загрузку сорока мегабайт на Яндекс.Диск.
 * Поэтому снимок живёт только на том телефоне, где его сняли, и приложение
 * говорит об этом прямо, а не делает вид, что копия его спасёт.
 *
 * Хранилище отдельное от анализов: список анализов читается на каждом открытии
 * экрана, и тянуть за ним мегабайты незачем.
 */
export interface LabPhoto {
  id: string
  /** К какому анализу — `LabTest.id`. */
  labId: string
  /** К какому результату, если снимок сделан вместе с ним. */
  resultId?: string
  /** День, которым снимок подписан. */
  day: number
  /** Сам снимок. Уменьшенный: с камеры приходит 12 мегапикселей. */
  blob: Blob
  width: number
  height: number
  bytes: number
  updatedAt?: number
}
