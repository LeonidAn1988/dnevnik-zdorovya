    await page.evaluate(async()=>{window.failGraves=true;await window.backup.saveNow();await window.backup.shareNow()})
    assert.equal(await page.evaluate(()=>window.savedFiles.length+window.sharedFiles.length),0)
    assert.equal(await page.evaluate(()=>window.settings.backupLastSignature),signature)
    await page.evaluate(async()=>{window.failGraves=false;await window.backup.saveNow();await window.backup.shareNow()})
    assert.equal(await page.evaluate(()=>window.savedFiles[0].tombstones[0].id),'new-grave')
    assert.equal(await page.evaluate(()=>window.sharedFiles[0].tombstones[0].id),'new-grave')
