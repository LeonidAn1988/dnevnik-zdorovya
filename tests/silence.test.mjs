/**
 * Молчание в чужом дневнике.
 *
 * «Отец перестал мерить», «отец не отмечает приём» и «у отца отвалился ключ» на
 * телефоне сына выглядят одинаково: данные есть. Говорим только о записях —
 * не о человеке и не о его здоровье.
 */
import { silence, silenceText, SILENCE_DAYS } from './build/api.mjs'

const ДЕНЬ = 24 * 60 * 60 * 1000
const сейчас = Date.UTC(2026, 8, 10, 12, 0, 0)

export function run() {
  let failures = 0
  const check = (name, condition, detail = '') => {
    if (condition) console.log(`  ok   ${name}`)
    else {
      console.log(`  FAIL ${name}${detail ? ' — ' + detail : ''}`)
      failures++
    }
  }

  const люди = [
    { id: 'p1', name: 'Я', deviceUser: 1 },
    { id: 'p2', name: 'Отец' },
  ]
  const изм = (person, дней) => ({ id: `r-${person}-${дней}`, kind: 'bp', ts: сейчас - дней * ДЕНЬ, sys: 130, dia: 80, bpm: 70, user: 1, person })
  // Курс приёма, а не коробка: отметки с 0.27.0 живут в нём. Имя оставлено
  // прежним — проверка та же, изменился только носитель отметок.
  const короб = (person, отмеченДней) => ({
    id: `r-${person}`, medicineId: `m-${person}`, person, times: ['09:00'], perTime: 1,
    taken: отмеченДней === null ? [] : [сейчас - отмеченДней * ДЕНЬ],
  })

  // Свежие записи — молчания нет.
  check(
    'вчерашние записи молчанием не считаются',
    silence(люди, [изм('p2', 1)], [короб('p2', 1)], 'p1', сейчас).length === 0,
  )

  // Четыре дня без измерений — говорим.
  const молчит = silence(люди, [изм('p2', 4)], [короб('p2', 0)], 'p1', сейчас)
  check('четыре дня без измерений видно', молчит.length === 1 && молчит[0].bp.days === 4)
  check('про приём молчания нет — отмечен сегодня', молчит[0].intake === undefined)
  check('назван тот человек', молчит[0].person.id === 'p2')

  // Про себя не говорим никогда — даже когда у себя всё молчит десять дней.
  const свои = silence(люди, [изм('p1', 10)], [короб('p1', 10)], 'p1', сейчас)
  check('о себе не говорим', !свои.some((s) => s.person.id === 'p1'), свои.map((s) => s.person.id).join(','))
  check('о ком не спрашивали — не говорим', silence([люди[0]], [изм('p1', 10)], [], 'p1', сейчас).length === 0)

  // Приём молчит, давление свежее.
  const приём = silence(люди, [изм('p2', 0)], [короб('p2', 6)], 'p1', сейчас)
  check('шесть дней без отметок видно', приём.length === 1 && приём[0].intake.days === 6)
  check('давление при этом не поминаем', приём[0].bp === undefined)

  // Коробок нет — про приём молчим, даже если отметок нет.
  const безКоробок = silence(люди, [изм('p2', 0)], [], 'p1', сейчас)
  check('без коробок про приём не говорим', безКоробок.length === 0)

  // Записей не было вовсе — это тот же вопрос «дошло ли».
  const пусто = silence(люди, [], [], 'p1', сейчас)
  check('дневник пуст — говорим', пусто.length === 1 && пусто[0].bp !== undefined && пусто[0].bp.days === null)
  check('без коробок про приём молчим и в пустом дневнике', пусто[0].intake === undefined)

  check('порог по умолчанию три дня', SILENCE_DAYS === 3)
  check('порог можно сдвинуть', silence(люди, [изм('p2', 4)], [], 'p1', сейчас, 7).length === 0)

  // ── тексты ──
  check('ни одной записи', silenceText(null, 'bp') === 'измерений нет ни одной')
  check('вчера', silenceText(1, 'bp') === 'измерений нет со вчера')
  check('склонение дней', silenceText(4, 'bp') === 'измерений нет 4 дня' && silenceText(11, 'bp') === 'измерений нет 11 дней')
  check('сегодня — молчать не о чем', silenceText(0, 'bp') === null)
  check('про приём свой текст', silenceText(6, 'intake') === 'отметок приёма нет 6 дней')
  check('в тексте нет упрёка и здоровья', !/не мерил|забыл|перестал|здоров/i.test(silenceText(4, 'bp')))

  return failures
}
