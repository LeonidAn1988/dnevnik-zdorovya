/** Generate shared CSS roles from the reviewed design tokens. */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
const source = JSON.parse(readFileSync(new URL('../design-exploration/dark-themes.json', import.meta.url)))
const light = {
  journal: { canvas:'#F6F2EA', surface:'#FFFCF6', raised:'#FFFFFF', text:'#1D2D25', secondary:'#4D5F51', primary:'#245B48', primaryHover:'#1C4B3A', primaryPressed:'#153B2D', onPrimary:'#FFFFFF', accent:'#245B48', selected:'#E2EBDC', controlBorder:'#72806F', divider:'#D9DED4', focus:'#245B48', highlight:'#EDF0E4', disabledSurface:'#E5E6DE', disabledText:'#586250' },
  rhythm: { canvas:'#F3F5FA', surface:'#FFFFFF', raised:'#FFFFFF', text:'#122237', secondary:'#4D607A', primary:'#244DDD', primaryHover:'#1F42BE', primaryPressed:'#19369D', onPrimary:'#FFFFFF', accent:'#2449C7', selected:'#E3EAFD', controlBorder:'#71809A', divider:'#DDE4EF', focus:'#244DDD', highlight:'#EDF1FD', disabledSurface:'#E5EAF2', disabledText:'#52627C' },
  clear: { canvas:'#F4F7F6', surface:'#FFFFFF', raised:'#FFFFFF', text:'#152524', secondary:'#4B635F', primary:'#006E65', primaryHover:'#005D55', primaryPressed:'#004D47', onPrimary:'#FFFFFF', accent:'#005A54', selected:'#DCEFEB', controlBorder:'#687F79', divider:'#DCE4E1', focus:'#006E65', highlight:'#E8F3F1', disabledSurface:'#E3EBE8', disabledText:'#536963' },
}
const alias = { page:'canvas', surface:'surface', field:'surface', 'text-primary':'text', 'text-secondary':'secondary', 'text-muted':'secondary', placeholder:'secondary', accent:'primary', 'accent-hover':'primaryHover', 'accent-ink':'onPrimary', 'accent-text':'accent', 'accent-quiet':'selected', 'border-strong':'controlBorder', border:'divider', grid:'divider', axis:'controlBorder', hover:'selected', 'appearance-focus':'focus', 'appearance-raised':'raised', 'appearance-highlight':'highlight', 'appearance-disabled':'disabledSurface', 'appearance-disabled-text':'disabledText' }
const concepts = ":is([data-interface='journal'], [data-interface='rhythm'], [data-interface='clear'])"
const lines = ['/* Generated by tools/build-appearance.mjs. Edit reviewed tokens/source. */', '@media screen {']
for (const theme of source.themes) {
  lines.push("  :root[data-interface='" + theme.id + "'] {", '    --appearance-page-light: ' + light[theme.id].canvas + ';', '    --appearance-page-dark: ' + theme.tokens.canvas + ';')
  for (const [role,value] of Object.entries(light[theme.id])) lines.push('    --appearance-light-' + role + ': ' + value + ';')
  for (const [role,value] of Object.entries(theme.tokens)) lines.push('    --appearance-dark-' + role + ': ' + value + ';')
  lines.push('  }')
}
function mappings(selector, dark) {
  lines.push('  ' + selector + ' {')
  for (const [role,primitive] of Object.entries(alias)) lines.push('    --' + role + ': var(--appearance-' + (dark?'dark':'light') + '-' + primitive + ');')
  const statuses = dark
    ? { good:'#A8DCB5', 'good-text':'#A8DCB5', warning:'#F2C66E', 'warning-text':'#F2C66E', critical:'#FFB4AB', 'critical-text':'#FFB4AB' }
    : { good:'#24633C', 'good-text':'#24633C', warning:'#805700', 'warning-text':'#805700', critical:'#A52B32', 'critical-text':'#A52B32' }
  for (const [role,value] of Object.entries(statuses)) lines.push('    --' + role + ': ' + value + ';')
  if (dark) {
    for (const [role,token] of Object.entries({ 'series-sys':'chart1', 'series-dia':'chart2', 'series-bpm':'chart3' })) lines.push('    --' + role + ': ' + source.common[token] + ';')
  }
  lines.push('    color-scheme: ' + (dark?'dark':'light') + ';', '  }')
}
mappings(':root' + concepts, false)
lines.push('  @media (prefers-color-scheme: dark) {')
mappings(':root:not([data-theme=light])' + concepts, true)
lines.push('  }')
mappings(':root[data-theme=dark]' + concepts, true)
lines.push('}')
for (const theme of source.themes) {
  const selector = ".appearance-preview[data-style='" + theme.id + "']"
  lines.push(selector + ' {')
  for (const role of ['canvas','text','primary','onPrimary','secondary','selected']) {
    lines.push('  --preview-' + role + ': ' + light[theme.id][role] + ';')
    lines.push('  --preview-dark-' + role + ': ' + theme.tokens[role] + ';')
  }
  lines.push('}')
}
const previewDark = ['canvas','text','primary','onPrimary','secondary','selected'].map(role =>
  '  --preview-' + role + ': var(--preview-dark-' + role + ');').join('\n')
lines.push('@media (prefers-color-scheme: dark) { :root:not([data-theme=light]) .appearance-preview {\n' + previewDark + '\n} }')
lines.push(':root[data-theme=dark] .appearance-preview {\n' + previewDark + '\n}')
mkdirSync(new URL('../src/styles', import.meta.url), { recursive:true })
writeFileSync(new URL('../src/styles/appearance-colors.css', import.meta.url), lines.join('\n')+'\n')
console.log('Appearance colors generated for ' + source.themes.length + ' concepts.')
