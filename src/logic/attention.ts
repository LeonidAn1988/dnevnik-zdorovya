/**
 * Что в дневнике ждёт решения — и где оно лежит.
 *
 * Точка внимания раньше зажигалась там, где о ней вспомнили: одна на шапке
 * «Настроек», две на нижних вкладках, каждая от своего условия. Цепочка от
 * этого разошлась молча — просроченная копия зажигала шапку, но внутри все
 * девять строк настроек выглядели одинаково, и куда идти, человек не знал. А
 * обновление не зажигало вовсе ничего: карточку на «Обзоре» пролистали — и
 * всё, найти её больше негде.
 *
 * Здесь это один список: каждое дело само говорит, в каком разделе, на каком
 * подэкране и в какой его части живёт. Шапка, вкладки, строки настроек и
 * полоса аптечки читают **один и тот же** список и спрашивают его про своё
 * место. Пока так, правило «подсвечено сверху — подсвечено и внутри»
 * выполняется само, а не держится на памяти того, кто правит код.
 *
 * Чистый модуль: ни разметки, ни хранилища — только правила.
 */

/** Какое дело ждёт. По ключу его находят проверки и экраны. */
export type AttentionKey = 'backup' | 'namesakes' | 'update' | 'stock' | 'restock' | 'intake'

export interface Attention {
  key: AttentionKey
  /** Раздел: нижняя вкладка или кнопка шапки. */
  tab: string
  /** Подэкран внутри раздела. Пусто — дело лежит прямо в разделе. */
  sub?: string
  /** Часть экрана: раздел полосы в аптечке. */
  section?: string
  /**
   * Чем это дело кончится, если его сделать, — короткой строкой.
   *
   * Идёт и в подпись точки для чтения с экрана, и в строку под названием
   * пункта. Цветная точка молчит, а «требует решения» не говорит ничего: в
   * настройках девять строк, и человеку нужна та, где написано, что именно
   * ждёт.
   */
  title: string
}

/** Из чего складывается список. Всё — уже посчитанное, здесь только правила. */
export interface AttentionInput {
  /** Копия дневника устарела или её нет вовсе. */
  backup: 'never' | 'behind' | 'stale' | null
  /** Имена, которые носят двое и больше. */
  namesakes: readonly string[]
  /** Сколько выпусков вышло после установленного. */
  updates: number
  /** Коробок с предупреждением: кончается, кончилось, просрочено. */
  alerts: number
  /** Коробок в списке покупок. */
  restock: number
  /** Приёмов, не отмеченных сегодня. */
  pending: number
}

const КОПИЯ: Record<'never' | 'behind' | 'stale', string> = {
  never: 'копии дневника ещё не было',
  behind: 'в копию не попали свежие записи',
  stale: 'копия устарела',
}

/**
 * Всё, что ждёт решения, — сверху вниз по важности.
 *
 * Порядок не косметика: когда одно место собирает несколько дел, показывается
 * первое, а первым должно стоять то, чья цена выше. Потерянный дневник дороже
 * непрочитанного описания выпуска.
 */
export function attentionOf(input: AttentionInput): Attention[] {
  const дела: Attention[] = []

  if (input.backup) {
    дела.push({ key: 'backup', tab: 'settings', sub: 'backup', title: КОПИЯ[input.backup] })
  }
  if (input.namesakes.length > 0) {
    дела.push({
      key: 'namesakes',
      tab: 'settings',
      sub: 'people',
      title: `двое с одним именем: ${input.namesakes.join(', ')}`,
    })
  }
  if (input.updates > 0) {
    дела.push({
      key: 'update',
      tab: 'settings',
      sub: 'about',
      title: input.updates === 1 ? 'вышла новая версия' : `вышло ${input.updates} обновления`,
    })
  }
  if (input.pending > 0) {
    дела.push({ key: 'intake', tab: 'intake', title: `осталось отметить: ${input.pending}` })
  }
  // Аптечка собирает два разных дела и разводит их по своим разделам: коробка
  // с предупреждением лежит в «Коробках», а список покупок — в «Купить», и
  // точка на вкладке без этого вела в раздел, где искомого нет.
  if (input.alerts > 0) {
    дела.push({ key: 'stock', tab: 'cabinet', section: 'boxes', title: `требуют внимания: ${input.alerts}` })
  }
  if (input.restock > 0) {
    дела.push({ key: 'restock', tab: 'cabinet', section: 'buy', title: `купить: ${input.restock}` })
  }

  return дела
}

/** Первое дело этого раздела. `null` — раздел чист. */
export function attentionIn(список: readonly Attention[], tab: string): Attention | null {
  return список.find((a) => a.tab === tab) ?? null
}

/** Первое дело этого подэкрана. По нему помечается строка в списке настроек. */
export function attentionAt(список: readonly Attention[], sub: string): Attention | null {
  return список.find((a) => a.sub === sub) ?? null
}

/** Первое дело этой части экрана: раздела полосы в аптечке. */
export function attentionOn(список: readonly Attention[], section: string): Attention | null {
  return список.find((a) => a.section === section) ?? null
}
