/**
 * Схема приёма с меняющейся дозой.
 *
 * Врач назначает «первую неделю по половине, потом по целой» и так же отменяет.
 * Ошибка здесь — это принятая не та доза, поэтому проверяется каждая граница с
 * обеих сторон, а заодно то, что расход и остаток считаются по дозе того дня, а
 * не по одной на всё время.
 */
import {
  stageOn, doseChangeOn, perTimeOf, perDayOf as _perDayOf, projectedLeft as _projectedLeft, dosesOn,
  formatCount, markTakenAt as _markTakenAt, splitBox, dosing,
} from './build/api.mjs'

/*
 * Фикстуры плоские, как препарат выглядел до 0.27.0. Раскладывает их тот же
 * `splitBox`, что и обновление базы: здесь проверяется схема доз, а не способ
 * хранения.
 */
const разложить = (m) => {
  const { box, regimen } = splitBox(m, 'p1')
  const курс = regimen ?? { id: `r-${box.id}`, medicineId: box.id, person: 'p1' }
  return { box, курс, приём: dosing(box, курс) }
}
const perDayOf = (m, day) => _perDayOf(разложить(m).приём, day ?? Date.now())
const projectedLeft = (m, now) => { const { box, приём } = разложить(m); return _projectedLeft(box, [приём], now) }
const markTakenAt = (m, planned, now) => {
  const { box, курс, приём } = разложить(m)
  const { box: b, regimen: r } = _markTakenAt(box, курс, [приём], planned, now)
  return { ...b, ...r }
}

const ДЕНЬ = 24 * 60 * 60 * 1000
const старт = new Date(2026, 8, 1).setHours(0, 0, 0, 0)
const день = (n) => старт + n * ДЕНЬ

/** Наращивание: неделя по половине, неделя по целой, дальше по полторы. */
const наращивание = {
  id: 'm1', name: 'Конкор', times: ['08:00'], perTime: 1, left: 60, packSize: 60, leftAt: старт,
  since: старт, planFrom: старт,
  plan: [{ perTime: 0.5, days: 7 }, { perTime: 1, days: 7 }, { perTime: 1.5, days: null }],
}
/** Отмена: неделя по целой, неделя по половине, дальше не принимаем. */
const отмена = {
  id: 'm2', name: 'Преднизолон', times: ['08:00'], perTime: 1, left: 30, packSize: 30, leftAt: старт,
  since: старт, planFrom: старт,
  plan: [{ perTime: 1, days: 7 }, { perTime: 0.5, days: 7 }],
}

export function run() {
  let failures = 0
  const check = (name, condition, detail = '') => {
    if (condition) console.log(`  ok   ${name}`)
    else {
      console.log(`  FAIL ${name}${detail ? ' — ' + detail : ''}`)
      failures++
    }
  }

  // ── границы этапов ───────────────────────────────────────────────────────
  check('первый день — первый этап', stageOn(наращивание, день(0)).perTime === 0.5)
  check('шестой день — ещё первый этап', stageOn(наращивание, день(6)).perTime === 0.5)
  check('седьмой день — второй этап', stageOn(наращивание, день(7)).perTime === 1)
  check('тринадцатый — ещё второй', stageOn(наращивание, день(13)).perTime === 1)
  check('четырнадцатый — третий', stageOn(наращивание, день(14)).perTime === 1.5)
  check('через год — всё ещё третий, он бессрочный', stageOn(наращивание, день(365)).perTime === 1.5)
  check('бессрочный этап не кончается', stageOn(наращивание, день(365)).finished === false)
  check('до начала схемы этапа нет', stageOn(наращивание, день(-1)) === null)
  check('без схемы этапа нет', stageOn({ id: 'x', name: 'Без схемы', perTime: 2 }, день(3)) === null)

  // ── конец курса ──────────────────────────────────────────────────────────
  check('в последний день курса доза ещё есть', stageOn(отмена, день(13)).perTime === 0.5)
  check('на следующий день курс окончен', stageOn(отмена, день(14)).finished === true)
  check('после окончания доза ноль', stageOn(отмена, день(14)).perTime === 0)
  check('после окончания приёмов в дне нет', dosesOn(отмена, день(20), день(20)).length === 0)
  check('во время курса приём есть', dosesOn(отмена, день(3), день(3)).length === 1)

  // ── доза дня ─────────────────────────────────────────────────────────────
  check('доза берётся на день', perTimeOf(наращивание, день(0)) === 0.5 && perTimeOf(наращивание, день(7)) === 1)
  check('без дня — обычная доза коробки', perTimeOf(наращивание) === 1)
  check('суточный расход считается по дозе дня', perDayOf(наращивание, день(0)) === 0.5 && perDayOf(наращивание, день(14)) === 1.5)

  // ── смена дозы называется ────────────────────────────────────────────────
  check('в день перехода видно, что доза меняется', JSON.stringify(doseChangeOn(наращивание, день(7))) === '{"from":0.5,"to":1}')
  check('внутри этапа ничего не меняется', doseChangeOn(наращивание, день(8)) === null)
  check('без схемы смены нет', doseChangeOn({ id: 'x', name: 'Без схемы' }, день(7)) === null)

  // ── остаток считается по схеме, а не по одной дозе ───────────────────────
  // Считаем на полдень пятнадцатого дня, приём в 08:00 уже прошёл:
  // 7 дней по 0,5 + 7 дней по 1 + один по 1,5 = 12 из 60.
  const остаток = projectedLeft(наращивание, день(14) + 12 * 60 * 60 * 1000)
  check('расход считается по дозе каждого дня', Math.abs(остаток - 48) < 0.001, String(остаток))
  // Без схемы — по одной штуке все пятнадцать дней.
  const безСхемы = projectedLeft({ ...наращивание, plan: undefined, planFrom: undefined }, день(14) + 12 * 60 * 60 * 1000)
  check('без схемы расход прежний', Math.abs(безСхемы - 45) < 0.001, String(безСхемы))

  // ── отметка списывает дозу того дня ──────────────────────────────────────
  const отмечен = markTakenAt(наращивание, день(0) + 8 * 60 * 60 * 1000, день(0) + 9 * 60 * 60 * 1000)
  check('отметка в первую неделю списывает половину', Math.abs(отмечен.left - 59.5) < 0.001, String(отмечен.left))

  // ── половинки пишутся дробью ─────────────────────────────────────────────
  check('половина', formatCount(0.5) === '½')
  check('полторы', formatCount(1.5) === '1½')
  check('целое без хвоста', formatCount(2) === '2')
  check('прочие дроби через запятую', formatCount(0.25) === '0,25')

  return failures
}
