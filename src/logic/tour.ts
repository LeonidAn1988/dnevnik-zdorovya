/**
 * Гайд-курс: подсветка настоящих кнопок с объяснением, что они делают.
 *
 * Приложение отдают друзьям и родителям, и первый вопрос у них один и тот же —
 * «а где тут что». Письменная инструкция на этот вопрос не отвечает: её не
 * читают, а если читают, то не сопоставляют слова с экраном. Поэтому курс
 * ведёт по живому приложению: сам открывает нужный раздел, затемняет всё
 * лишнее и обводит ту самую кнопку, о которой говорит.
 *
 * **Курсов несколько, и каждый короткий.** Один список из двадцати шагов
 * бросают на пятом: человек не знает, сколько ещё, и не понимает, зачем ему
 * про сахар, если он ведёт только давление. Здесь курс — это один вопрос
 * («как записать давление», «где что настроить»), четыре–шесть шагов, и его
 * видно целиком в заголовке: «шаг 3 из 5».
 *
 * **Шаг без своего элемента пропускается молча.** Половина кнопок появляется
 * не всегда: аптек может не быть выбрано, людей — один, напоминаний в браузере
 * нет вовсе. Курс, который упирается в отсутствующую кнопку и замирает, хуже
 * отсутствия курса, поэтому шаг здесь — пожелание, а не требование.
 */

import type { Settings } from '../types'
import { visibleSections } from './settings'
import { toolLabels } from './nav'

/** Один шаг: что открыть, что обвести и что сказать. */
export interface TourStep {
  /**
   * Раздел, который курс открывает перед шагом.
   *
   * Ключ вкладки или служебного раздела — те же строки, что и в навигации
   * приложения. Пусто — остаёмся там, где были.
   */
  tab?: string
  /** Значение `data-tour` у элемента, который обводим. */
  target: string
  title: string
  text: string
}

/** Курс: один вопрос, на который он отвечает. */
export interface Tour {
  key: string
  title: string
  /** Строкой под названием: о чём этот курс. */
  hint: string
  steps: TourStep[]
}

/** Что курс должен знать о приложении, чтобы не звать в несуществующее. */
export interface TourContext {
  /** Есть ли в этой сборке настоящие напоминания. В браузере их нет. */
  reminders: boolean
}

