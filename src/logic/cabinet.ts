/**
 * Аптечка как инвентарь: поиск по своим коробкам и назначение-категория.
 *
 * Аптечка стала общей на дом (0.27.0), и в ней сразу оказалось два десятка
 * коробок на четверых. Пролистать их глазами ещё можно, а вот ответить «есть
 * ли у нас что-то от давления» или «не лежит ли где амлодипин» — уже нет.
 *
 * **Поиск здесь свой, а не `searchHits` из `drugs.ts`.** Тот про реестр: в нём
 * тридцать пять тысяч записей, кэш нормализованных строк в `WeakMap` и порог в
 * два символа, чтобы не перебирать всё на первой букве. В аптечке коробок
 * пятнадцать, кэш не нужен, а порог в один символ полезен: «д» в своём списке
 * — осмысленный запрос.
 *
 * **Где здесь черта.** Категория — это полка в шкафу, а не диагноз. «Давление»
 * значит «мы держим это от давления», а не «вам показано при гипертонии».
 * Подсказка появляется при заведении препарата и правится руками; в уже
 * заведённые коробки она не проставляется молча и при показе не додумывается.
 * Та же черта, что в §11 бэклога: приложение сообщает факт о собственном
 * списке человека и на этом останавливается.
 */

import type { Medicine } from '../types'
import { normalize } from './drugs'
import { substances } from './duplicates'
import type { Stock } from './medicines'

/** Чем совпало — строка результата объясняет, почему коробка нашлась. */
export type MatchField = 'name' | 'inn' | 'dose' | 'maker' | 'note' | 'purpose'

export interface CabinetHit {
  item: Stock
  field: MatchField
}

/**
 * Порог поиска — один символ.
 *
 * В реестре он два: там на первой букве пришлось бы перебрать тридцать пять
 * тысяч записей. Здесь коробок полтора десятка, и «д» — это законный запрос:
 * человек начинает набирать и сразу видит, как список сужается.
 */
export const MIN_QUERY = 1

/**
 * Поиск по аптечке.
 *
 * Корзины по убыванию точности: начало названия, включение в название,
 * действующее вещество, дозировка, производитель, примечание, категория.
 * Порядок не косметический — он отвечает на вопрос «что я искал вероятнее
 * всего»: набрав «кон», человек ищет «Конкор», а не «Тамифлю» с примечанием
 * «при контакте с больным».
 *
 * Вещество разбирается на части: «амлодипин» обязан находить коробку, где в
 * реестре записано «Амлодипин + Периндоприл». Ровно тот случай, ради которого
 * сверка по веществу и делалась, только с другой стороны.
 */
export function searchStock(items: Stock[], query: string): CabinetHit[] {
  const игла = normalize(query)
  if (игла.length < MIN_QUERY) return []

  // Семь корзин по числу полей, в порядке точности.
  const корзины: CabinetHit[][] = [[], [], [], [], [], [], []]

  for (const item of items) {
    const box = item.box
    const имя = normalize(box.name)

    if (имя.startsWith(игла)) {
      корзины[0].push({ item, field: 'name' })
      continue
    }
    if (имя.includes(игла)) {
      корзины[1].push({ item, field: 'name' })
      continue
    }
    // Вещество — и целиком, и по частям комбинации.
    const вещества = substances(box.inn)
    if (normalize(box.inn ?? '').includes(игла) || вещества.some((в) => normalize(в).includes(игла))) {
      корзины[2].push({ item, field: 'inn' })
      continue
    }
    if (normalize(box.dose).includes(игла)) {
      корзины[3].push({ item, field: 'dose' })
      continue
    }
    if (normalize(box.maker ?? '').includes(игла)) {
      корзины[4].push({ item, field: 'maker' })
      continue
    }
    if (normalize(box.note ?? '').includes(игла)) {
      корзины[5].push({ item, field: 'note' })
      continue
    }
    if (normalize(box.purpose ?? '').includes(игла)) {
      корзины[6].push({ item, field: 'purpose' })
    }
  }

  return корзины.flat()
}

/** Подпись, объясняющая совпадение. `null` — совпало название, объяснять нечего. */
export function matchNote(hit: CabinetHit): string | null {
  const box = hit.item.box
  switch (hit.field) {
    case 'inn':
      return box.inn ? `по веществу: ${box.inn}` : null
    case 'dose':
      return box.dose ? `по дозировке: ${box.dose}` : null
    case 'maker':
      return box.maker ? `по производителю: ${box.maker}` : null
    case 'note':
      return box.note ? `по примечанию: ${box.note}` : null
    case 'purpose':
      return box.purpose ? `по категории: ${box.purpose}` : null
    default:
      return null
  }
}

