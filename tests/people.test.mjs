/**
 * Люди отдельно от памяти прибора.
 *
 * Главное, что проверяется, — обновление ничего не ломает у того, кто вёл
 * дневник на себя одного. Он не заводил никаких людей, а после обновления они
 * появились; если при этом его аптечка окажется ничьей или дневник давления
 * опустеет, это будет выглядеть как потеря данных, а не как новая возможность.
 */
import { firstPerson, activePersonOf, ownerOf, medicinesOf, deviceUserOf, freeDeviceUsers, newPersonId, defaultPersonId, intakeTimesOf, ПЕРВЫЙ,
  intakeSlotsOf,
  setIntakeSlots,
  newSlotId
} from './build/api.mjs'

export function run() {
  let failures = 0
  const check = (name, condition, detail = '') => {
    if (condition) console.log(`  ok   ${name}`)
    else {
      console.log(`  FAIL ${name}${detail ? ' — ' + detail : ''}`)
      failures++
    }
  }

  // ── первый человек ───────────────────────────────────────────────────────
  const изКоробки = firstPerson({ userNames: { 1: 'Пользователь 1', 2: 'Пользователь 2' }, activeUser: 1 }, 'установка-1')
  check('подпись из коробки именем не считается', изКоробки.name === ПЕРВЫЙ, изКоробки.name)
  check('первый привязан к памяти прибора', изКоробки.deviceUser === 1)

  const своё = firstPerson({ userNames: { 1: 'Леонид', 2: '' }, activeUser: 1 }, 'установка-1')
  check('своё имя переносится', своё.name === 'Леонид')

  const второй = firstPerson({ userNames: { 1: 'Пользователь 1', 2: 'Отец' }, activeUser: 2 }, 'установка-1')
  check('берётся имя активного пользователя', второй.name === 'Отец' && второй.deviceUser === 2)

  check('пустая подпись именем не считается', firstPerson({ userNames: {}, activeUser: 1 }, 'установка-1').name === ПЕРВЫЙ)
  check('«Пользователь  2» с лишним пробелом тоже не имя', firstPerson({ userNames: { 1: 'Пользователь  2' }, activeUser: 1 }, 'установка-1').name === ПЕРВЫЙ)

  // Идентификатор первого человека уникален для установки: одинаковый на всех
  // телефонах ключ склеил бы разных людей при первом же семейном слиянии.
  const пч_один = firstPerson({ userNames: {}, activeUser: 1 }, 'установка-1')
  const пч_два = firstPerson({ userNames: {}, activeUser: 1 }, 'установка-2')
  check('первый человек не получает вечный p1', пч_один.id !== 'p1' && пч_два.id !== 'p1', пч_один.id)
  check('две установки — разные идентификаторы', пч_один.id !== пч_два.id)

  // Главное в этой починке: один телефон всегда даёт одного человека. Прежде
  // ключ брался от часов, и холодный старт заводил нового «Я» каждый раз —
  // у владельца так накопилось двое.
  check('то же зерно — тот же человек', firstPerson({ userNames: {}, activeUser: 1 }, 'установка-1').id === пч_один.id)
  check('ключ собирается из зерна', пч_один.id === defaultPersonId('установка-1'))
  check('без зерна откат на прежнее правило', defaultPersonId('').startsWith('p') && defaultPersonId('') !== 'p')
  check('пробелы в зерне не в счёт', defaultPersonId('  установка-1  ') === пч_один.id)

  // ── кто выбран ───────────────────────────────────────────────────────────
  const люди = [{ id: 'p1', name: 'Я', deviceUser: 1 }, { id: 'p2', name: 'Жена' }]
  check('выбранный находится', activePersonOf({ people: люди, activePerson: 'p2' })?.name === 'Жена')
  check('пропавший выбранный подменяется первым', activePersonOf({ people: люди, activePerson: 'нет-такого' })?.id === 'p1')
  check('без людей выбирать некого', activePersonOf({ people: [], activePerson: 'p1' }) === null)

  // ── чей препарат ─────────────────────────────────────────────────────────
  const ничей = { id: 'm1', name: 'Конкор' }
  const чужой = { id: 'm2', name: 'Метформин', owner: 'p2' }
  check('препарат без владельца достаётся первому', ownerOf(ничей, люди) === 'p1')
  check('владелец уважается', ownerOf(чужой, люди) === 'p2')
  check('без людей владельца нет', ownerOf(ничей, []) === null)

  // Владелец, которого удалили. Окно подтверждения обещает, что препараты
  // перейдут первому, — здесь это и должно случиться. Иначе коробка остаётся за
  // призраком и пропадает из аптечки у всех сразу.
  const призрак = { id: 'm3', name: 'Метформин', owner: 'p-удалённый' }
  check('владелец-призрак заменяется первым', ownerOf(призрак, люди) === 'p1')
  check('препарат призрака виден первому', medicinesOf([призрак], люди, 'p1').length === 1)
  check('и не виден второму', medicinesOf([призрак], люди, 'p2').length === 0)

  // Главное для обновления: пока человек один, аптечка не фильтруется вовсе.
  check('у одного человека видна вся аптечка',
    medicinesOf([ничей, чужой], [люди[0]], 'p1').length === 2)
  check('у двоих аптечка делится', medicinesOf([ничей, чужой], люди, 'p1').map((m) => m.id).join() === 'm1')
  check('второму достаётся своё', medicinesOf([ничей, чужой], люди, 'p2').map((m) => m.id).join() === 'm2')

  // ── память прибора ───────────────────────────────────────────────────────
  check('у человека с прибором память есть', deviceUserOf(люди[0]) === 1)
  check('у человека без прибора памяти нет', deviceUserOf(люди[1]) === null)
  check('без человека памяти нет', deviceUserOf(null) === null)

  // Занятую память нельзя выдать второму: иначе два дневника давления сольются
  // в один, и чьё измерение — не разобрать.
  check('свободна только вторая', freeDeviceUsers(люди).join() === '2')
  check('своя память остаётся своей при правке', freeDeviceUsers(люди, 'p1').join() === '1,2')
  check('обе заняты — свободных нет',
    freeDeviceUsers([{ id: 'a', name: 'A', deviceUser: 1 }, { id: 'b', name: 'B', deviceUser: 2 }]).length === 0)

  // ── часы приёма ──────────────────────────────────────────────────────────
  // У отца утро в шесть, у сына в девять — общие часы означают, что одному из
  // них придётся вводить время руками для каждого лекарства.
  const общие = { morning: '08:00', day: '13:00', evening: '19:00', night: '22:00' }
  const свои = { morning: '06:00', day: '12:00', evening: '18:00', night: '21:00' }
  check('без своих часов берутся общие', intakeTimesOf({ id: 'p1', name: 'Я' }, общие).morning === '08:00')
  check('свои часы главнее общих', intakeTimesOf({ id: 'p2', name: 'Отец', intakeTimes: свои }, общие).morning === '06:00')
  check('без человека тоже общие', intakeTimesOf(null, общие).night === '22:00')

  check('идентификаторы разные', newPersonId(1) !== newPersonId(2))


  // ── кнопки приёма ────────────────────────────────────────────────────────
  const сл_часы = { morning: '08:00', day: '13:00', evening: '19:00', night: '22:00' }
  const сл_один = { people: [{ id: 'p1', name: 'Я', deviceUser: 1 }], intakeTimes: сл_часы }
  check('без своих кнопок — четыре исходных из часов', intakeSlotsOf(null, сл_один).map((x) => x.time).join() === '08:00,13:00,19:00,22:00')
  const сл_правка = setIntakeSlots(сл_один, 'p1', [{ id: 'morning', title: 'Утром', time: '07:00' }])
  check('одиночке кнопки пишутся в общие настройки', сл_правка.intakeSlots?.length === 1 && сл_правка.intakeTimes?.morning === '07:00')
  check('удалённая кнопка не сдвигает старое время', сл_правка.intakeTimes?.day === '13:00')
  const сл_семья = { people: [{ id: 'p1', name: 'Я', deviceUser: 1 }, { id: 'p-dad', name: 'Отец', deviceUser: 2 }], intakeTimes: сл_часы }
  const сл_отцу = setIntakeSlots(сл_семья, 'p-dad', [{ id: 'morning', title: 'Утром', time: '06:30' }])
  check('в семье правка отцу не трогает общие часы', сл_отцу.intakeTimes === undefined)
  check('и пишется самому отцу', сл_отцу.people?.find((p) => p.id === 'p-dad')?.intakeTimes?.morning === '06:30')
  check('у «Я» часы прежние', intakeSlotsOf(сл_отцу.people?.find((p) => p.id === 'p1') ?? null, { ...сл_семья, ...сл_отцу })[0].time === '08:00')
  check('новый ключ кнопки уникален во времени', newSlotId(1000) !== newSlotId(1001))

  return failures
}
