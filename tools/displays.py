#!/usr/bin/env python3
"""Набор снимков семисегментных экранов: качалка и опись.

Зачем отдельный инструмент, а не «скачал руками». Набор данных живёт вне
репозитория — это сотни мегабайт, — и единственное, что остаётся в git, это
опись источников с лицензиями. Через год вопрос «откуда взялись эти снимки и
что с ними можно делать» задаст либо магазин, либо своя же совесть, и ответ
должен быть в репозитории, а не в памяти.

    python3 tools/displays.py список          # что есть, что скачано
    python3 tools/displays.py качать          # всё из корзины А
    python3 tools/displays.py качать 7seg-ocr # один источник

Куда кладём: `tools/out/displays/<ключ>/`. Каталог `tools/out/` уже в
`.gitignore` и уже служит кэшем сборщиков справочников — набор данных ведёт себя
так же: восстанавливается скриптом, потерять не жалко.

**Чего этот скрипт не делает.** Не качает источник без лицензии в описи и не
качает корзину «В» вовсе. Это не бюрократия: лицензия набора наследуется
обученной на нём моделью, а модель поедет в приложение, которое собирается в
магазины. Разбираться с этим потом дороже, чем записать сейчас.

Свои снимки сюда не кладутся. Они невосстановимы, и место им в хабе
результатов, а не в каталоге, который чистится одной командой.
"""

import json
import sys
import urllib.request
from pathlib import Path

ОПИСЬ = Path(__file__).with_name('displays.json')
КУДА = Path('tools/out/displays')
# Свои снимки — в хаб: их не пересобрать, и `tools/out` для них не место.
СВОИ = Path.home() / 'Claude_Projects/Результаты/дневник-здоровья/снимки-тонометров'


def опись() -> list[dict]:
    return json.loads(ОПИСЬ.read_text(encoding='utf-8'))['источники']


def размер(путь: Path) -> int:
    return sum(f.stat().st_size for f in путь.rglob('*') if f.is_file()) if путь.exists() else 0


def по_человечески(байт: int) -> str:
    for единица, порог in (('ГБ', 1 << 30), ('МБ', 1 << 20), ('КБ', 1 << 10)):
        if байт >= порог:
            return f'{байт / порог:.1f} {единица}'
    return f'{байт} Б'


def список() -> None:
    всего = 0
    for и in опись():
        папка = КУДА / и['ключ']
        есть = размер(папка)
        всего += есть
        метка = по_человечески(есть) if есть else '—'
        print(f"  {и['ключ']:<20} корзина {и['корзина']}  {и['лицензия']:<16} {метка:>9}  {и['что']}")
        if и['корзина'] != 'А':
            print(f"      ↳ {и['заметка']}")
    print(f"\n  скачано всего: {по_человечески(всего)} в {КУДА}")
    свои = размер(СВОИ)
    print(f"  свои снимки:   {по_человечески(свои)} в {СВОИ}" if свои else
          f"  свои снимки:   пока нет — ждём их в {СВОИ}")


def качать(ключи: list[str]) -> int:
    бед = 0
    for и in опись():
        if ключи and и['ключ'] not in ключи:
            continue
        if not ключи and и['корзина'] != 'А':
            continue
        if и['корзина'] == 'В':
            print(f"  пропуск {и['ключ']}: корзина В — {и['заметка']}")
            continue
        if и['лицензия'] in ('не указана', 'не считана'):
            print(f"  пропуск {и['ключ']}: лицензия не выяснена, качать нельзя")
            бед += 1
            continue
        if not и.get('файлы'):
            # Корзина правильная, а прямой ссылки нет: у Roboflow выгрузка идёт
            # через ключ бесплатного аккаунта. Молчать об этом нельзя — иначе
            # выглядит так, будто источник скачан.
            print(f"  пропуск {и['ключ']}: прямой ссылки нет — {и['заметка']}")
            continue
        папка = КУДА / и['ключ']
        папка.mkdir(parents=True, exist_ok=True)
        for адрес in и.get('файлы', []):
            цель = папка / адрес.rsplit('/', 1)[-1]
            if цель.exists():
                print(f"  уже есть {цель} ({по_человечески(цель.stat().st_size)})")
                continue
            print(f"  качаю {и['ключ']}: {адрес}")
            try:
                # Через временное имя: оборванная закачка не должна выглядеть
                # как готовый файл при следующем запуске.
                временно = цель.with_suffix(цель.suffix + '.part')
                with urllib.request.urlopen(адрес, timeout=120) as ответ, временно.open('wb') as f:
                    while кусок := ответ.read(1 << 20):
                        f.write(кусок)
                временно.rename(цель)
                print(f"    готово: {по_человечески(цель.stat().st_size)}")
            except Exception as ошибка:  # noqa: BLE001 — причина печатается целиком
                print(f"    не вышло: {ошибка}")
                бед += 1
    return бед


if __name__ == '__main__':
    команда = sys.argv[1] if len(sys.argv) > 1 else 'список'
    if команда == 'список':
        список()
    elif команда == 'качать':
        код = качать(sys.argv[2:])
        sys.exit(1 if код else 0)
    else:
        print(__doc__)
        sys.exit(2)
