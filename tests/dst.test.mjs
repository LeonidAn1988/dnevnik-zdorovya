/**
 * Перевод часов: сутки бывают по 23 и по 25 часов.
 *
 * В аптечке сутки местами считались миллисекундами — `начало + дней * 86 400 000`.
 * В ночь перевода такая арифметика промахивается на час, а поскольку сравнение
 * идёт с местной полуночью, промах превращается в целый день: этап схемы
 * длится на сутки дольше, и человек принимает прежнюю дозу, когда назначена
 * уже другая. Для гипертоника это ошибка вдвое.
 *
 * В России часы не переводят с 2014 года, поэтому здесь это спит. Проснётся
 * у того, кто уехал, и на macOS с Windows, куда проект собирается.
 *
 * **Как проверять.** Даты ниже — настоящие границы перевода в Европе:
 * 29 марта 2026 (сутки 23 часа) и 25 октября 2026 (сутки 25 часов). В зоне без
 * перевода это обычные дни, и проверки всё равно осмысленны — они про
 * календарные сутки. В зоне с переводом они и ловят промах:
 *
 *     npm run test:dst
 */
import { stageOn, projectedLeft, dosesOn, perDayOf } from './build/api.mjs'

const полночь = (y, m, d) => new Date(y, m, d).setHours(0, 0, 0, 0)

const коробка = (f) => ({ id: 'k1', name: 'Метформин', dose: '850 мг', left: null, expires: null, ...f })
const приём = (короб, курс) => ({
  boxId: короб.id, regimenId: 'r1', name: короб.name, dose: короб.dose,
  left: короб.left, leftAt: короб.leftAt, expires: короб.expires, person: 'p1', ...курс,
})

export function run() {
  let failures = 0
  const check = (name, condition, detail = '') => {
    if (condition) console.log(`  ok   ${name}`)
    else {
      console.log(`  FAIL ${name}${detail ? ' — ' + detail : ''}`)
      failures++
    }
  }

  const зонаСПереводом =
    new Date(2026, 0, 15).getTimezoneOffset() !== new Date(2026, 6, 15).getTimezoneOffset()
  console.log(`  ·    зона ${зонаСПереводом ? 'с переводом часов' : 'без перевода'} (${Intl.DateTimeFormat().resolvedOptions().timeZone})`)

  // ── этап схемы через весеннюю ночь ───────────────────────────────────────
  // Этап на семь дней с 25 марта кроет 25–31 марта. Первое апреля — уже
  // следующий этап. С арифметикой в миллисекундах граница уезжала на час
  // вперёд, и первого апреля человек оставался на прежней дозе.
  const весна = {
    plan: [{ days: 7, perTime: 1 }, { days: null, perTime: 2 }],
    planFrom: полночь(2026, 2, 25),
    perTime: 1,
  }
  check('в первый день этапа — первый этап', stageOn(весна, полночь(2026, 2, 25))?.index === 0)
  check('в последний день этапа — ещё он же', stageOn(весна, полночь(2026, 2, 31))?.index === 0,
    String(stageOn(весна, полночь(2026, 2, 31))?.index))
  check(
    'на следующий день после перевода — уже второй этап',
    stageOn(весна, полночь(2026, 3, 1))?.index === 1,
    `этап ${stageOn(весна, полночь(2026, 3, 1))?.index}`,
  )
  check('и доза выросла вдвое', stageOn(весна, полночь(2026, 3, 1))?.perTime === 2)

  // ── этап через осеннюю ночь ──────────────────────────────────────────────
  // 25 октября сутки длиннее, и промах идёт в другую сторону: этап кончался
  // на день раньше срока.
  const осень = {
    plan: [{ days: 7, perTime: 1 }, { days: null, perTime: 2 }],
    planFrom: полночь(2026, 9, 21),
    perTime: 1,
  }
  check('осенью последний день этапа на месте', stageOn(осень, полночь(2026, 9, 27))?.index === 0,
    String(stageOn(осень, полночь(2026, 9, 27))?.index))
  check('и следующий начинается вовремя', stageOn(осень, полночь(2026, 9, 28))?.index === 1)

  // ── расход за период с переводом ─────────────────────────────────────────
  // Семь дней по таблетке — семь таблеток, сколько бы часов ни было в сутках.
  const короб = коробка({ left: 30, leftAt: полночь(2026, 2, 25) })
  const курс = приём(короб, { times: ['08:00'], perTime: 1, since: полночь(2026, 2, 25) })
  check(
    'за семь дней ушло семь таблеток, а не шесть и не восемь',
    projectedLeft(короб, [курс], полночь(2026, 3, 1)) === 23,
    String(projectedLeft(короб, [курс], полночь(2026, 3, 1))),
  )
  const короб2 = коробка({ left: 30, leftAt: полночь(2026, 9, 21) })
  const курс2 = приём(короб2, { times: ['08:00'], perTime: 1, since: полночь(2026, 9, 21) })
  check(
    'осенью тоже семь',
    projectedLeft(короб2, [курс2], полночь(2026, 9, 28)) === 23,
    String(projectedLeft(короб2, [курс2], полночь(2026, 9, 28))),
  )

  // ── ритм через перевод ───────────────────────────────────────────────────
  // «Через день» считается по календарным суткам: в ночь перевода счёт не
  // должен сбиться, иначе приём уедет на соседний день и останется там.
  const черезДень = приём(коробка({ left: 30 }), {
    times: ['08:00'], perTime: 1, since: полночь(2026, 2, 25),
    rhythm: { onDays: 1, offDays: 1, from: полночь(2026, 2, 25) },
  })
  const дни = [25, 26, 27, 28, 29, 30, 31].map((d) => dosesOn(черезДень, полночь(2026, 2, d), полночь(2026, 2, d)).length)
  check('через день остаётся через день и в ночь перевода', дни.join() === '1,0,1,0,1,0,1', дни.join())

  // ── расход в день у схемы ────────────────────────────────────────────────
  check('расход на границе этапов берётся от нужного этапа',
    perDayOf(приём(коробка({ left: 30 }), { ...весна, times: ['08:00'] }), полночь(2026, 3, 1)) === 2,
    String(perDayOf(приём(коробка({ left: 30 }), { ...весна, times: ['08:00'] }), полночь(2026, 3, 1))))

  return failures
}
