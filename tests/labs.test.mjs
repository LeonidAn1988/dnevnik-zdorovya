/**
 * Анализы: сроки, напоминания и бюджет будильников.
 *
 * Главное здесь — не расписание само по себе, а то, что оно не съедает
 * напоминания о таблетках. Анализ редок, но если считать его «ставкой в день»,
 * горизонт приёмов у семьи из пяти обрушивается с десяти дней до четырёх, и
 * человек перестаёт получать напоминания к концу недели. Поэтому последняя
 * проверка в этом файле — про горизонт, и посчитана она руками.
 */
import {
  dueOf,
  occurrencesOf,
  resultFor,
  lastResult,
  nextDue,
  labState,
  describeDue,
  describeFrozen,
  sortLabs,
  labsOf,
  labsDue,
  buildLabReminders,
  labId,
  LAB_ID_BASE,
  LAB_ID_MAX,
  MAX_LAB_REMINDERS,
  MEASURE_ID_MAX,
  planReminders,
  mergeLab,
  WINDOW_DAYS,
} from './build/api.mjs'

const ДЕНЬ = 24 * 60 * 60 * 1000
const старт = new Date(2026, 9, 1).setHours(0, 0, 0, 0) // 1 октября 2026
const день = (n) => new Date(new Date(старт).setDate(new Date(старт).getDate() + n)).setHours(0, 0, 0, 0)

const анализ = (f) => ({ id: 't1', name: 'ТТГ', owner: 'p1', results: [], ...f })
const результат = (f) => ({ id: 'r1', day: старт, values: [2.1], ...f })
const курс = (f) => ({ id: 'k1', medicineId: 'm1', person: 'p1', ...f })

export function run() {
  let failures = 0
  const check = (name, condition, detail = '') => {
    if (condition) console.log(`  ok   ${name}`)
    else {
      console.log(`  FAIL ${name}${detail ? ' — ' + detail : ''}`)
      failures++
    }
  }

  // ── дата сдачи ───────────────────────────────────────────────────────────
  check('без расписания даты нет', dueOf(анализ({})) === null)
  check('своя дата берётся как есть', dueOf(анализ({ schedule: { due: день(5) } }))?.at === день(5))

  // Привязка к курсу: пока курс жив и у него есть конец, дата считается от него.
  const скурсом = анализ({ schedule: { due: старт, afterRegimen: 'k1', afterDays: 14 } })
  const живой = [курс({ endsAt: день(10) })]
  check('дата считается от конца курса', dueOf(скурсом, живой)?.at === день(24), String(dueOf(скурсом, живой)?.at))
  check('и это не заморозка', dueOf(скурсом, живой)?.frozen === false)
  // Курс исчез — дата не исчезает вместе с ним: анализ никуда не делся.
  check('курса нет — дата остаётся последней посчитанной', dueOf(скурсом, [])?.at === старт)
  check('и приложение знает, что она заморожена', dueOf(скурсом, [])?.frozen === true)
  check('у бессрочного курса тоже заморозка', dueOf(скурсом, [курс({})])?.frozen === true)
  check('и об этом сказано словами', (describeFrozen(скурсом, []) ?? '').includes('курса больше нет'))
  check('у живой привязки слов нет', describeFrozen(скурсом, живой) === null)

  // ── повторы ──────────────────────────────────────────────────────────────
  const раз = анализ({ schedule: { due: день(3) } })
  check('без повтора дата одна', occurrencesOf(раз, [], старт, день(400)).length === 1)
  const ежемесячно = анализ({ schedule: { due: день(3), everyMonths: 1 } })
  const даты = occurrencesOf(ежемесячно, [], старт, день(100))
  check('раз в месяц даёт четыре даты за сто дней', даты.length === 4, String(даты.length))
  check('первая — назначенная', даты[0] === день(3))
  check('вторая — через месяц по календарю', даты[1] === new Date(2026, 10, 4).setHours(0, 0, 0, 0),
    new Date(даты[1]).toDateString())
  const каждые10 = анализ({ schedule: { due: день(0), everyDays: 10 } })
  check('раз в десять дней', occurrencesOf(каждые10, [], старт, день(25)).map((d) => (d - старт) / ДЕНЬ).join() === '0,10,20')
  // Просроченная дата обязана попасть в список: о ней и надо напомнить.
  const просрочен = анализ({ schedule: { due: день(-5) } })
  check('просроченная дата не теряется', occurrencesOf(просрочен, [], старт, день(30))[0] === день(-5))

  // ── результат закрывает сдачу ────────────────────────────────────────────
  const сдал = анализ({ schedule: { due: старт }, results: [результат({ day: день(3) })] })
  check('результат в окне закрывает назначенную сдачу', !!resultFor(сдал, старт))
  check('и окно ровно две недели', WINDOW_DAYS === 14)
  const поздно = анализ({ schedule: { due: старт }, results: [результат({ day: день(15) })] })
  check('результат позже окна её не закрывает', resultFor(поздно, старт) === null)
  // Сходил раньше срока — сдача закрыта. Приложение, которое после этого
  // звонит в день сдачи, звонит ровно тому, кто всё сделал вовремя.
  const рано = анализ({ schedule: { due: день(5) }, results: [результат({ day: старт })] })
  check('сданное раньше срока закрывает сдачу', !!resultFor(рано, день(5)))
  // Но окно повторяющегося анализа урезано до половины промежутка: иначе одна
  // запись закрыла бы сразу две сдачи, и человек увидел бы «сдано» там, где не
  // сдавал. Повтор раз в десять дней — окно пять.
  const частый = анализ({ schedule: { due: день(10), everyDays: 10 }, results: [результат({ day: старт })] })
  check('чужая сдача соседнюю не закрывает', resultFor(частый, день(10)) === null,
    JSON.stringify(resultFor(частый, день(10))))
  check('а своя — закрывает', !!resultFor(анализ({ schedule: { due: день(3), everyDays: 10 }, results: [результат({ day: старт })] }), день(3)))
  check('последний результат — самый поздний',
    lastResult(анализ({ results: [результат({ id: 'a', day: старт }), результат({ id: 'b', day: день(9) })] }))?.id === 'b')

  // ── следующая несданная ──────────────────────────────────────────────────
  const месячный = анализ({ schedule: { due: старт, everyMonths: 1 }, results: [результат({ day: старт })] })
  check('сданная дата пропускается', nextDue(месячный, [], старт) === new Date(2026, 10, 1).setHours(0, 0, 0, 0),
    new Date(nextDue(месячный, [], старт)).toDateString())
  check('у разового сданного следующей нет', nextDue(сдал, [], день(4)) === null)

  // ── состояние и слова ────────────────────────────────────────────────────
  check('сегодня', labState(анализ({ schedule: { due: старт } }), [], старт) === 'сегодня')
  check('впереди', labState(анализ({ schedule: { due: день(3) } }), [], старт) === 'впереди')
  check('просрочен', labState(просрочен, [], старт) === 'просрочен')
  check('сдан', labState(сдал, [], день(4)) === 'сдан')
  check('без расписания состояния нет', labState(анализ({}), [], старт) === 'нет срока')
  check('словами: сегодня', describeDue(анализ({ schedule: { due: старт } }), [], старт) === 'Сдать сегодня')
  check('словами: завтра', describeDue(анализ({ schedule: { due: день(1) } }), [], старт) === 'Сдать завтра')
  check('словами: дата', describeDue(анализ({ schedule: { due: день(5) } }), [], старт) === 'Сдать 6 октября',
    String(describeDue(анализ({ schedule: { due: день(5) } }), [], старт)))
  // Склонение — то, обо что спотыкаются все: «просрочен на 1 день», «на 2 дня»,
  // «на 5 дней», «на 11 дней», «на 21 день».
  const про = (n) => describeDue(анализ({ schedule: { due: день(-n) } }), [], старт)
  check('склонение: 1 день', про(1) === 'Просрочен на 1 день', String(про(1)))
  check('склонение: 2 дня', про(2) === 'Просрочен на 2 дня', String(про(2)))
  check('склонение: 5 дней', про(5) === 'Просрочен на 5 дней', String(про(5)))
  check('склонение: 11 дней', про(11) === 'Просрочен на 11 дней', String(про(11)))
  check('склонение: 21 день', про(21) === 'Просрочен на 21 день', String(про(21)))

  // ── порядок и отбор ──────────────────────────────────────────────────────
  const список = [
    анализ({ id: 'a', name: 'Впереди', schedule: { due: день(9) } }),
    анализ({ id: 'b', name: 'Просрочен', schedule: { due: день(-2) } }),
    анализ({ id: 'c', name: 'Сегодня', schedule: { due: старт } }),
    анализ({ id: 'd', name: 'Без срока' }),
  ]
  check('сначала горящее', sortLabs(список, [], старт).map((t) => t.id).join() === 'b,c,a,d',
    sortLabs(список, [], старт).map((t) => t.id).join())
  check('свои анализы отбираются по человеку',
    labsOf([анализ({ id: 'x', owner: 'p1' }), анализ({ id: 'y', owner: 'p2' })], 'p2').map((t) => t.id).join() === 'y')
  check('горящие — это просроченные и сегодняшние',
    labsDue(список, [], старт).map((t) => t.id).sort().join() === 'b,c')

  // ── напоминания ──────────────────────────────────────────────────────────
  const subject = (test, i = 0) => ({ test, person: test.owner, name: null, index: 0, testIndex: i })
  const вперёд = анализ({ schedule: { due: день(5), time: '09:00' } })
  const набор = buildLabReminders([subject(вперёд)], [], старт)
  check('три момента на сдачу', набор.length === 3, String(набор.length))
  check('первый — накануне вечером', new Date(набор[0].at).getHours() === 18 && набор[0].at < день(5))
  check('второй — в день сдачи', new Date(набор[1].at).getHours() === 9 && набор[1].at > день(5) && набор[1].at < день(6))
  check('третий — через два дня', набор[2].at > день(7) && набор[2].at < день(8))
  check('род — анализ', набор.every((r) => r.kind === 'lab'))
  // Отмечать в уведомлении нечего: результат приходит из лаборатории. Без этого
  // признака отложенное «напомни позже» от таблеток снималось бы чужим ключом.
  check('отмечать нечего', набор.every((r) => r.markable === false))
  check('повторов через 15 минут нет', new Set(набор.map((r) => r.at)).size === 3)
  check('номера свои и различны', new Set(набор.map((r) => r.id)).size === 3)
  check('номера в своём диапазоне', набор.every((r) => r.id > MEASURE_ID_MAX && r.id <= LAB_ID_MAX))
  check('диапазон начинается сразу за измерениями', LAB_ID_BASE === MEASURE_ID_MAX + 1)
  check('и не доходит до отложенных', LAB_ID_MAX < 20_000_000)
  check('номер разный у разных анализов', labId(старт, 0, 0, 0) !== labId(старт, 1, 0, 0))
  check('и у разных людей', labId(старт, 0, 0, 0) !== labId(старт, 0, 0, 1))
  check('и у разных дней', labId(старт, 0, 0, 0) !== labId(день(1), 0, 0, 0))

  check('прошлые моменты не ставятся', buildLabReminders([subject(вперёд)], [], день(6)).length === 1)
  // Сходил раньше назначенного — звонить нечего. Это главный случай, ради
  // которого окно смотрит и назад: человек всё сделал, а телефон его дёргает.
  check('сдавшему раньше срока не напоминаем',
    buildLabReminders([subject(анализ({ schedule: { due: день(5) }, results: [результат({ day: день(1) })] }))], [], старт).length === 0)
  check('и сдавшему в срок тоже',
    buildLabReminders([subject(анализ({ schedule: { due: день(5) }, results: [результат({ day: день(5) })] }))], [], старт).length === 0)
  check('без расписания напоминаний нет', buildLabReminders([subject(анализ({}))], [], старт).length === 0)

  // Потолок: пятнадцать анализов по три момента — ровно сорок пять.
  const много = Array.from({ length: 20 }, (_, i) =>
    subject(анализ({ id: `t${i}`, name: `Анализ ${i}`, schedule: { due: день(5 + i) } }), i))
  check('набор упирается в потолок', buildLabReminders(много, [], старт).length === MAX_LAB_REMINDERS,
    String(buildLabReminders(много, [], старт).length))
  check('и ближайшие остаются', buildLabReminders(много, [], старт)[0].at < день(6))

  // ── бюджет: анализы не съедают горизонт таблеток ─────────────────────────
  // Семья из пяти, у каждого по два приёма в день с повтором трижды: это сорок
  // напоминаний в сутки. Без анализов горизонт — 400/40 = 10 дней.
  const приём = (i) => ({
    boxId: `b${i}`, regimenId: `r${i}`, name: `Таблетка ${i}`, dose: '1 мг',
    person: `p${i % 5}`, times: ['08:00', '20:00'], perTime: 1, left: 100, expires: null,
  })
  const семья = Array.from({ length: 5 }, (_, i) => приём(i))
  // `personOf` обязателен: без него пять препаратов пяти человек схлопываются
  // в два общих напоминания на весь дом, и «семья из пяти» в проверке
  // перестаёт быть семьёй из пяти.
  const настройки = { repeat: true, personOf: (m) => m.person, personName: (id) => id }
  const без = planReminders({ medicines: семья, subjects: [], now: старт, options: настройки })
  // Считаем дни именно таблеточных напоминаний: горизонт — это про них.
  // Считать все подряд нельзя — анализы расставляются на шестьдесят дней
  // вперёд, и любой обвал горизонта таблеток тонул бы в их датах.
  const дней = (набор) =>
    new Set(набор.filter((r) => r.kind === 'dose').map((r) => new Date(r.at).toDateString())).size
  check('без анализов горизонт десять дней', дней(без) === 10, String(дней(без)))

  // Те же таблетки плюс пятнадцать анализов вразнобой: сорок пять напоминаний
  // вычитаются целым числом, остаётся 355, то есть восемь полных суток.
  const анализы = Array.from({ length: 15 }, (_, i) =>
    subject(анализ({ id: `L${i}`, name: `Анализ ${i}`, owner: `p${i % 5}`, schedule: { due: день(3 + i) } }), i % 8))
  const с = planReminders({ medicines: семья, subjects: [], labs: анализы, now: старт, options: настройки })
  check('с анализами горизонт не обваливается', дней(с) >= 8, String(дней(с)))
  // Горизонт считается целыми сутками, поэтому сорок пять занятых мест стоят
  // двух дней, а не одного: 355/40 = 8,875 → восемь. Это цена простоты, и она
  // измерена: восемь дней вместо десяти, а не четыре.
  check('горизонт теряет не больше двух дней', дней(без) - дней(с) <= 2, `${дней(без)} → ${дней(с)}`)
  check('и остаток бюджета не пропадает зря', с.length >= 355, String(с.length))
  check('анализы в набор попали', с.some((r) => r.kind === 'lab'))
  check('общий потолок не превышен', с.length <= 400, String(с.length))
  // Наивный путь — считать анализ ставкой в день — дал бы 400/(40+15)=7 дней и
  // меньше. Проверка именно на это: горизонт таблеток не должен упасть ниже
  // девяти, пока анализов не больше пятнадцати.
  check('горизонт не падает до наивных семи', дней(с) > 7, String(дней(с)))

  // ── слияние ──────────────────────────────────────────────────────────────
  const мой = анализ({ results: [результат({ id: 'a', day: старт })], updatedAt: 10 })
  const чужой = анализ({ results: [результат({ id: 'b', day: день(30) })], updatedAt: 20 })
  const слит = mergeLab(мой, чужой)
  check('результаты складываются, а не заменяются', слит?.results.length === 2, String(слит?.results.length))
  check('и идут по дате', слит?.results.map((r) => r.id).join() === 'a,b')
  check('одинаковое слияние ничего не меняет', mergeLab(мой, мой) === null)
  const переименован = анализ({ name: 'ТТГ и Т4', results: [результат({ id: 'a', day: старт })], updatedAt: 30 })
  check('имя берётся у свежего', mergeLab(мой, переименован)?.name === 'ТТГ и Т4')

  return failures
}
