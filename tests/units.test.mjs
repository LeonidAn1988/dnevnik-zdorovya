/**
 * Единицы измерения по форме выпуска.
 *
 * Главное здесь — капли: единица приёма и единица упаковки у них разные, и без
 * пересчёта флакон в десять миллилитров «кончался» за пять приёмов по две
 * капли. Остальные формы проверяются на то, что подпись сменилась, а
 * арифметика осталась прежней.
 */
import {
  unitsOf, dosesPerPackUnit, needsDropSize, doseUnit, packUnit, toPackUnits, dosesInPack, DROPS_PER_ML,
  perDayOf, supplyDays, projectedLeft, buildMemo, restockText, restockList, doseAmount,
} from './build/api.mjs'

const ДЕНЬ = 24 * 60 * 60 * 1000
const день = (г, м, д) => new Date(г, м, д).getTime()

const препарат = (fields) => ({
  id: 'u1', name: 'Проба', dose: '', left: null, perDay: null, expires: null, ...fields,
})

export function run() {
  let failures = 0
  const check = (name, condition, detail = '') => {
    if (condition) console.log(`  ok   ${name}`)
    else {
      console.log(`  FAIL ${name}${detail ? ' — ' + detail : ''}`)
      failures++
    }
  }

  // ── подписи по форме ────────────────────────────────────────────────────
  check('без формы выпуска — штуки, как было всегда', packUnit(препарат({})) === 'шт.')
  check('таблетки — штуки', packUnit(препарат({ form: 'Таблетки, покрытые пленочной оболочкой' })) === 'шт.')
  check('капли — миллилитры в упаковке', packUnit(препарат({ form: 'Капли для приема внутрь [масляные]' })) === 'мл')
  check('сироп — миллилитры', packUnit(препарат({ form: 'Сироп' })) === 'мл')
  check('ампулы', packUnit(препарат({ form: 'Раствор для инъекций' })) === 'амп.')
  check('спрей — дозы', packUnit(препарат({ form: 'Спрей назальный дозированный' })) === 'доз')
  check('мазь — граммы', packUnit(препарат({ form: 'Мазь для наружного применения' })) === 'г')

  const капли = препарат({ form: 'Капли для приема внутрь [масляные]' })
  check('у капель приём считается каплями', unitsOf(капли).dose[2] === 'капель')
  check('склонение: 1 капля', doseUnit(капли, 1) === 'капля')
  check('склонение: 2 капли', doseUnit(капли, 2) === 'капли')
  check('склонение: 5 капель', doseUnit(капли, 5) === 'капель')
  check('у таблеток склонять нечего', doseUnit(препарат({ form: 'Таблетки' }), 2) === 'шт.')
  check('подпись поля упаковки меняется', unitsOf(капли).packLabel === 'Миллилитров во флаконе')
  check('половина капли не отмеряется', unitsOf(капли).fractional === false)
  check('половина таблетки — отмеряется', unitsOf(препарат({ form: 'Таблетки' })).fractional === true)

  // ── пересчёт ────────────────────────────────────────────────────────────
  check('вопрос о каплях в миллилитре задаётся только каплям', needsDropSize(капли) && !needsDropSize(препарат({ form: 'Сироп' })))
  check('по умолчанию — фармакопейная капля', dosesPerPackUnit(капли) === DROPS_PER_ML && DROPS_PER_ML === 20)
  check('своё число капель побеждает', dosesPerPackUnit({ ...капли, dropsPerMl: 40 }) === 40)
  check('мусор вместо числа — обратно к двадцати', dosesPerPackUnit({ ...капли, dropsPerMl: 0 }) === 20)
  check('у таблеток пересчёта нет', dosesPerPackUnit(препарат({ form: 'Таблетки' })) === 1)

  check('две капли — это десятая миллилитра', Math.abs(toPackUnits(капли, 2) - 0.1) < 1e-9)
  check('у «Вигантола» с сорока каплями — двадцатая', Math.abs(toPackUnits({ ...капли, dropsPerMl: 40 }, 2) - 0.05) < 1e-9)
  check('две таблетки — это две таблетки', toPackUnits(препарат({ form: 'Таблетки' }), 2) === 2)
  check('во флаконе 10 мл около 200 капель', dosesInPack({ ...капли, packSize: 10 }) === 200)
  check('и 400 при масляной капле', dosesInPack({ ...капли, packSize: 10, dropsPerMl: 40 }) === 400)

  // ── что из этого следует в аптечке ──────────────────────────────────────
  const флакон = {
    ...капли,
    times: ['08:00'], perTime: 2, packSize: 10, left: 10,
    leftAt: день(2026, 8, 1), since: день(2026, 8, 1),
  }
  check('в сутки уходит десятая доля миллилитра', Math.abs(perDayOf(флакон) - 0.1) < 1e-9, String(perDayOf(флакон)))
  check('флакона хватает на сто дней, а не на пять', supplyDays(флакон) === 100, String(supplyDays(флакон)))

  const таблетки = { ...флакон, form: 'Таблетки', left: 10, packSize: 10 }
  // По две штуки за приём, приём один: десять таблеток — это пять дней.
  check('у таблеток счёт прежний, без пересчёта', supplyDays(таблетки) === 5, String(supplyDays(таблетки)))

  // Остаток через двадцать дней: двадцать приёмов по две капли — два миллилитра.
  const через20 = день(2026, 8, 21)
  check(
    'за двадцать дней уходит два миллилитра из десяти',
    Math.abs(projectedLeft(флакон, через20) - 8) < 1e-6,
    String(projectedLeft(флакон, через20)),
  )
  check(
    'а таблеток за те же дни — двадцать штук, то есть в ноль',
    projectedLeft(таблетки, через20) === 0,
    String(projectedLeft(таблетки, через20)),
  )

  // ── что из этого видно человеку ─────────────────────────────────────────
  {
    const флаконДляПамятки = {
      ...капли, name: 'Вигантол', times: ['08:00'], perTime: 2, packSize: 10, left: 10,
      leftAt: день(2026, 8, 1), since: день(2026, 8, 1), dropsPerMl: 40,
    }
    const памятка = buildMemo([флаконДляПамятки], [{ time: '08:00', title: 'Утро' }], день(2026, 8, 1))
    check('в памятке недельный счёт в каплях', памятка.totals[0].unit === 'капель', памятка.totals[0].unit)
    check('и это четырнадцать капель за неделю', памятка.totals[0].pieces === 14, String(памятка.totals[0].pieces))
    // Десять миллилитров при сорока каплях в мл — четыреста капель. Хватает.
    check('флакона на неделю хватает', памятка.totals[0].enough === true, String(памятка.totals[0].enough))

    const мало = buildMemo([{ ...флаконДляПамятки, left: 0.2 }], [{ time: '08:00', title: 'Утро' }], день(2026, 8, 1))
    check('а двух десятых миллилитра — нет', мало.totals[0].enough === false, String(мало.totals[0].enough))

    check('строка приёма называет каплю', doseAmount(капли, 1, '1') === '1 капля', doseAmount(капли, 1, '1'))
    check('а единственную таблетку не называет', doseAmount(препарат({ form: 'Таблетки' }), 1, '1') === '')

    // Пустой флакон попадает в список покупок — там единицы обязаны быть теми же.
    const кончился = { ...флаконДляПамятки, left: 0, leftAt: день(2026, 8, 1) }
    const покупки = restockText(restockList([кончился], день(2026, 8, 20)))
    check('в списке покупок миллилитры, а не штуки', покупки.includes('мл') && !покупки.includes('шт.'), покупки)
  }

  return failures
}
