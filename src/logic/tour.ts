/**
 * Какие курсы показывать этому человеку.
 *
 * Курс про давление не нужен тому, кто выключил раздел давления, а шаг про
 * напоминания — браузеру, где их нет. Отсеиваем сразу, а не показываем курс,
 * который на середине окажется пустым.
 */
export function tours(
  settings: Pick<Settings, 'sections' | 'trackGlucose' | 'people'>,
  context: TourContext = { reminders: true },
): Tour[] {
  const разделы = new Set<string>(visibleSections(settings))
  const список = [УСТРОЙСТВО]
  if (разделы.has('bp')) список.push(ДАВЛЕНИЕ)
  if (разделы.has('cabinet') || разделы.has('intake')) список.push(ЛЕКАРСТВА)
  список.push(НАСТРОЙКИ)

  return список
    .map((курс) => ({
      ...курс,
      steps: курс.steps.filter((шаг) => {
        if (шаг.target === 'set-reminders' && !context.reminders) return false
        // Кнопки выбора человека при одном человеке нет вовсе — и рассказывать
        // про неё нечего.
        if (шаг.target === 'person' && (settings.people?.length ?? 0) <= 1) return false
        if (шаг.tab && ['bp', 'cabinet', 'intake', 'overview', 'glucose'].includes(шаг.tab)) return разделы.has(шаг.tab)
        return true
      }),
    }))
    .filter((курс) => курс.steps.length > 0)
}

/** Курс по ключу — с теми же отсевами, что и в списке. */
export function tourByKey(
  key: string,
  settings: Pick<Settings, 'sections' | 'trackGlucose' | 'people'>,
  context?: TourContext,
): Tour | null {
  return tours(settings, context).find((курс) => курс.key === key) ?? null
}
