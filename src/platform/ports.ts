/**
 * Границы между переносимым ядром и платформой.
 *
 * Всё, что ядро умеет само — разбор пакетов прибора, классификация, статистика,
 * экспорт — не знает ни про браузер, ни про React. Платформа даёт ровно четыре
 * вещи, описанные ниже, и при переезде на Android, iOS, macOS и Windows меняются
 * только их реализации.
 *
 * Интерфейсы намеренно узкие: это ровно то, чем пользуется приложение, а не
 * пересказ Web Bluetooth или IndexedDB. Иначе порт перестаёт быть портом.
 */

import type { Measurement, Medicine, Regimen, Settings, Tombstone } from '../types'
import type { DiskFile } from '../logic/yandex'

// ── Bluetooth ──────────────────────────────────────────────────────────────

/** Характеристика GATT в объёме, который нужен протоколу Omron. */
export interface GattCharacteristic {
  readonly uuid: string
  /**
   * Запись с подтверждением. Протокол Omron синхронный: следующий кусок пакета
   * отправляется только после подтверждения предыдущего, поэтому запись без
   * подтверждения здесь не нужна и намеренно не предусмотрена.
   */
  writeValue(data: Uint8Array): Promise<void>
  startNotifications(onValue: (data: Uint8Array) => void): Promise<void>
  stopNotifications(): Promise<void>
}

export interface GattCharacteristicProperties {
  read: boolean
  write: boolean
  writeWithoutResponse: boolean
  notify: boolean
  indicate: boolean
}

export interface GattService {
  getCharacteristic(uuid: string): Promise<GattCharacteristic>
  /** Для диагностики: перечислить, что прибор на самом деле предоставляет. */
  listCharacteristics(): Promise<{ characteristic: GattCharacteristic; properties: GattCharacteristicProperties }[]>
}

export interface GattDevice {
  readonly id: string
  readonly name: string | null
  /** Подключается и отдаёт нужный сервис. Сервисы резолвятся не мгновенно — ждать внутри. */
  connect(serviceUuid: string): Promise<GattService>
  disconnect(): void
}

export interface DevicePickerOptions {
  /** Рабочий сервис: к нему подключаемся после выбора. */
  serviceUuid: string
  /**
   * Сервисы, которые прибор объявляет в рекламном пакете.
   *
   * Отдельно от рабочего, потому что совпадают они не всегда: тонометр Omron
   * вещает стандартный «Blood Pressure», а память отдаёт через фирменный
   * сервис, которого в эфире нет. Искать можно только по объявленному —
   * фильтр по рабочему не совпадёт ни с чем.
   *
   * Пусто — прибор объявляет свой рабочий сервис, и разделять нечего.
   */
  advertisedServices?: string[]
  /** Имена, под которыми прибор рекламируется в эфире. */
  namePrefixes: string[]
  /** Показать все устройства, а не только подходящие под фильтры. */
  showAll: boolean
}

export interface BluetoothPort {
  /** Есть ли вообще такая возможность на этой платформе. */
  isSupported(): boolean
  /** Включён ли радиомодуль. null — платформа не отвечает на этот вопрос. */
  isEnabled(): Promise<boolean | null>
  /**
   * Открывает выбор устройства. Обязан вызываться из обработчика жеста.
   *
   * Окно рисует платформа, и системным оно не является нигде: в браузере его
   * показывает сам браузер, на Android — плагин. Проверено на устройстве,
   * поэтому в текстах интерфейса «системное окно» заменено на «список».
   */
  pickDevice(options: DevicePickerOptions): Promise<GattDevice>
  /** Ранее разрешённые устройства — чтобы не спрашивать выбор каждый раз. */
  knownDevices(serviceUuid: string): Promise<GattDevice[]>

  /**
   * Мешает ли поиску выключенная служба местоположения.
   *
   * `true` — радиомодуль включён, разрешения выданы, но телефон всё равно не
   * отдаёт результаты поиска. Так ведут себя многие Android-телефоны: обещание
   * `neverForLocation` освобождает от разрешения на геолокацию, но не от
   * требования, чтобы сама служба была включена в системе.
   *
   * Без этой проверки человек видит пустой список и не понимает, почему прибор
   * «не находится», — а причина в системном переключателе, о котором никто не
   * догадается.
   *
   * `null` — вопрос к платформе неприменим (в браузере такого нет).
   */
  isLocationBlockingScan?(): Promise<boolean | null>

  /** Открыть системный экран, где это включается. */
  openLocationSettings?(): Promise<void>
  /** Отличить отказ пользователя от настоящей ошибки. */
  isCancellation(error: unknown): boolean
}

// ── хранилище ──────────────────────────────────────────────────────────────

export interface StoragePort {
  /**
   * Идентификатор этой установки приложения.
   *
   * Заводится один раз при первом обращении и живёт, пока живёт дневник.
   * Нужен семейному слиянию: пара «установка + человек» уникальна, даже если
   * на двух телефонах людей зовут одинаково.
   *
   * Лежит отдельно от настроек намеренно. Настройки целиком уезжают в копию
   * дневника, а копию наверняка будут использовать, чтобы настроить телефон
   * отца, — и обе установки в тот же день стали бы одной.
   */
  installId(): Promise<string>

  allMeasurements(): Promise<Measurement[]>
  /**
   * Записать измерения.
   *
   * `stamp` по умолчанию истинно: хранилище само ставит `updatedAt`. Ложно оно
   * только на одном пути — восстановлении из копии, где отметка приходит из
   * файла: пометив старую копию сегодняшним числом, приложение сделало бы её
   * свежее местных правок.
   */
  putMeasurements(items: Measurement[], stamp?: boolean): Promise<void>
  deleteMeasurement(id: string): Promise<void>
  /**
   * Вернуть только что удалённое измерение — вместе со снятием надгробия.
   *
   * Отдельный метод, а не повторная запись: `putMeasurements` намеренно не
   * пускает обратно то, у чего есть надгробие, иначе удалённое возвращалось бы
   * при каждой выгрузке с прибора. Кнопка «Вернуть» из-за этого молча не
   * работала: запись не возвращалась, а баннер закрывался как после успеха.
   *
   * Одной транзакцией: между снятием надгробия и записью приложение может
   * закрыться, и тогда удаление перестало бы быть удалением, не став возвратом.
   */
  restoreMeasurement(item: Measurement): Promise<void>
  clearMeasurements(): Promise<void>
  loadSettings(): Promise<Partial<Settings> | undefined>
  saveSettings(settings: Settings): Promise<void>

  allMedicines(): Promise<Medicine[]>
  /** `stamp` — как у измерений: ложно только при восстановлении из копии. */
  putMedicine(item: Medicine, stamp?: boolean): Promise<void>
  deleteMedicine(id: string): Promise<void>

  /**
   * Курсы приёма — отдельное хранилище, а не поле внутри коробки.
   *
   * Из одной коробки могут принимать двое, и курс кончается независимо от неё.
   * Пока они лежали вместе, аптечка не могла быть общей на дом.
   */
  allRegimens(): Promise<Regimen[]>
  putRegimen(item: Regimen, stamp?: boolean): Promise<void>
  deleteRegimen(id: string): Promise<void>

  /**
   * Следы удалённых записей.
   *
   * Хранятся отдельно от самих записей, а не полем `deleted` внутри них. Поле
   * пришлось бы отфильтровывать в каждом месте, где список читают, и первое же
   * забытое место показало бы человеку то, что он удалил. Отдельное хранилище
   * такой ошибки не допускает: удалённого в списках нет физически.
   */
  allTombstones(): Promise<Tombstone[]>
  putTombstones(items: Tombstone[]): Promise<void>

  /**
   * Попросить платформу не вытеснять наши данные.
   *
   * Браузер вправе очистить хранилище сайта, когда на устройстве кончается
   * место, а Safari стирает его сам после недели без заходов. Для дневника
   * измерений это тихая потеря, поэтому разрешение спрашивается сразу.
   *
   * Возвращает, действует ли защита. `null` — платформа такого не умеет и
   * вопрос к ней неприменим (на нативной, например, данные и так не вытесняются).
   */
  requestDurability(): Promise<boolean | null>
}

// ── файлы ──────────────────────────────────────────────────────────────────

export interface FilePort {
  /**
   * Открыть ссылку за пределами приложения.
   *
   * Отдельный метод, а не обычная ссылка: на Android её нужно отдать системе
   * с признаком «новая задача», иначе она открывается поверх приложения.
   * Чем открыть — решает система: стоит приложение аптеки, откроется оно.
   */
  openExternal(url: string): Promise<void>

  /**
   * Отдать пользователю файл: скачиванием, диалогом сохранения или «поделиться».
   *
   * `false` — файл до человека не дошёл: он закрыл окно, отменил сохранение.
   * Возврат обязателен именно потому, что на телефоне «сохранить» проходит
   * через системное окно, от которого можно отказаться. Считать такую попытку
   * успешной — значит записать в дневник, что копия сделана, когда её нет.
   */
  save(filename: string, content: string, mime: string): Promise<boolean>

  /**
   * Можно ли передать файл в другое приложение — в облако, мессенджер, почту.
   *
   * На телефоне это единственный способ вынести копию за пределы устройства:
   * скачанный файл остаётся в той же памяти, что и сам дневник, и пропадает
   * вместе с телефоном.
   */
  canShare(): boolean
  /** Системное «поделиться» файлом. `false` — пользователь закрыл окно. */
  share(filename: string, content: string, mime: string): Promise<boolean>

  /**
   * Поделиться текстом, а не файлом.
   *
   * Список покупок уходил файлом `купить.txt`, и в мессенджере получатель
   * видел вложение, которое надо открыть, — а не сообщение, которое читается
   * в ленте. Дневник по-прежнему уходит файлом: он и есть файл.
   */
  shareText(text: string, title: string): Promise<boolean>

  /** Скопировать текст. `false` — не вышло, и об этом надо сказать. */
  copyText(text: string): Promise<boolean>

  /**
   * Напечатать текущую страницу — она же «сохранить в PDF».
   *
   * Отдельно от `save`, потому что печатается не файл, который мы собрали, а
   * то, что человек видит на экране, со всей вёрсткой отчёта.
   *
   * Нужен именно порт: `window.print()` в браузере открывает диалог печати, а
   * внутри WebView не делает ничего — там это системная печать, которую
   * запускает нативный код. Кнопка, которая молча ничего не делает, хуже
   * отсутствующей, а отчёт врачу — то, ради чего дневник и ведут.
   *
   * `false` — человек закрыл диалог или печать недоступна.
   */
  print(jobName: string): Promise<boolean>
}

/**
 * Чем кончилась запись копии.
 *
 * Двух состояний не хватало: `write` возвращал `false` и когда доступ к файлу
 * отозван, и когда облачная папка просто недоступна без сети. Приложение
 * обходилось с ними одинаково — отвязывало файл, — и человек после поездки в
 * метро должен был заново его искать.
 */
export type BackupWriteResult =
  /** Записано. */
  | 'ok'
  /** Временно не вышло: файл на месте, доступ цел. Повторим при следующем изменении. */
  | 'retry'
  /** Цели больше нет: файл удалён или доступ отозван. Нужно выбирать заново. */
  | 'lost'

/**
 * Автоматические резервные копии в один и тот же файл.
 *
 * Отдельный порт, а не метод у FilePort: «отдать файл» это разовое действие по
 * нажатию, а здесь долгоживущая цель, в которую приложение пишет само и без
 * спроса. Не всякая платформа так умеет — в вебе это есть в Chrome на
 * компьютере, но не в Safari и не в мобильном Chrome, поэтому `isSupported`.
 */
export interface BackupPort {
  isSupported(): boolean
  /** Спросить у пользователя файл для копий. Обязан вызываться из обработчика жеста. */
  choose(suggestedName: string): Promise<string | null>
  /** Имя ранее выбранного файла, если он выбран и доступ к нему цел. */
  target(): Promise<string | null>
  /** Записать копию. */
  write(content: string): Promise<BackupWriteResult>
  /**
   * Прочитать копию из того же файла — чтобы вернуть дневник назад.
   *
   * Системный выбор файла это тоже умеет, но там человеку надо самому опознать
   * `дневник-копия.json` среди своих файлов. Тому, кто откатывает случайное
   * удаление, короткий путь важнее: файл уже выбран, приложение знает какой.
   * `null` — цели нет или файл не читается.
   */
  read(): Promise<string | null>
  /** Забыть цель — копии перестают делаться сами. */
  forget(): Promise<void>

  // ── чужие копии: семейная синхронизация ──────────────────────────────────
  //
  // Сервера нет: каждый телефон пишет свою копию в общую папку, а чужие копии
  // читает. Ничего, кроме чтения, здесь не нужно — портить чужой файл нам
  // нечем, и права записи на него приложение не просит.

  /** Умеет ли платформа держать список чужих файлов между запусками. */
  canReadSources(): boolean
  /** Спросить у человека чужой файл. `null` — отказался. Только из жеста. */
  addSource(): Promise<BackupSource | null>
  /** Подключённые чужие файлы. */
  sources(): Promise<BackupSource[]>
  /** Прочитать чужой файл. `null` — недоступен: удалён, переименован, отозван доступ. */
  readSource(id: string): Promise<string | null>
  /** Отключить чужой файл. Сам файл не трогаем: он не наш. */
  removeSource(id: string): Promise<void>
}

/**
 * Обмен через облако: приложение само ходит в папку семьи.
 *
 * Отдельный порт, а не часть `BackupPort`: там долгоживущий файл, выбранный
 * человеком в системном окне, здесь — сеть и ключ доступа. Скачивание
 * необязательно: в браузере его запрещает сам Яндекс (тело файла отдаёт другой
 * хост, и чужому сайту читать ответ он не даёт), поэтому веб отдаёт свой
 * дневник, но чужие не читает.
 */
export interface CloudPort {
  /** Ключ сохранён — обмен настроен. */
  token(): string | null
  /** Запомнить ключ. Пустая строка — отключить обмен. */
  setToken(value: string): void
  /** Умеет ли платформа читать чужие файлы. В браузере — нет. */
  canDownload(): boolean
  /** Что лежит в папке семьи. Ошибка сети — исключение, вызывающий решает. */
  list(): Promise<DiskFile[]>
  /** Записать свой дневник. */
  upload(name: string, content: string): Promise<void>
  /** Прочитать чужой. `null` — платформа не умеет или файл недоступен. */
  download(name: string): Promise<string | null>
  /**
   * Убрать свой прежний файл — в корзину Диска, не насовсем.
   *
   * Зовётся только для файлов с меткой этой установки: чужой дневник удалять
   * нечем и незачем. В корзину, потому что ошибиться здесь стоит чужого
   * дневника, а корзина Диска держит удалённое тридцать дней.
   */
  remove(name: string): Promise<void>
}

/** Чужая копия: `id` — для приложения, `name` — чтобы человек узнал файл. */
export interface BackupSource {
  id: string
  name: string
}

// ── напоминания ────────────────────────────────────────────────────────────

/**
 * Одно напоминание — на конкретный момент, а не «каждый день в восемь».
 *
 * Повторяющееся ежедневное уведомление выглядит проще и не годится: у него нет
 * отдельного сегодняшнего экземпляра, поэтому снять оставшиеся повторы после
 * отметки о приёме нечем. Здесь каждое напоминание знает свои сутки и свой
 * приём, и набор пересобирается целиком при любой отметке.
 */
/**
 * О чём напоминание: принять таблетки или измерить давление.
 *
 * Род обязан доходить до платформы, а не оставаться в ядре. Кнопка «Принял» в
 * шторке решает по одному лишь `actionId`, и без рода нажатие на карточке
 * измерения отметило бы приём таблеток — время 08:00 у приёма стоит по
 * умолчанию, так что совпадение здесь не край, а норма.
 */
export type ReminderKind = 'dose' | 'measure'

export interface Reminder {
  /** Свой идентификатор: платформа адресует напоминания числами, не строками. */
  id: number
  kind: ReminderKind
  title: string
  /** Одна строка: столько и покажет свёрнутое уведомление. */
  body: string
  /** Полный состав приёма с дозировками — для развёрнутого вида. */
  details: string
  /**
   * Есть ли в этом приёме хоть один препарат, который человек отмечает руками.
   *
   * Автосписываемые отметки не требуют по определению, и слот с одним таким
   * препаратом не «закрывается» никогда. Без этого признака отложенное «напомни
   * позже» висело бы вечно: ждать от человека нечего, а пара «день + приём»
   * формально жива.
   */
  markable: boolean
  /** Момент показа. */
  at: number
  /** К какому приёму относится: «08:00». */
  slot: string
  /** Начало суток этого приёма. */
  day: number
  /** 0 — напоминание в назначенное время, дальше повторы. */
  step: number
  /** Чьи таблетки — идентификатор человека. Пусто, когда человек в дневнике один. */
  person?: string
}

/**
 * Что человек сделал с уведомлением.
 *
 * `open` — нажал на само уведомление: ждёт экран, где ставится отметка.
 * `taken` — нажал кнопку «Принял» прямо в уведомлении.
 *
 * «Отложить» сюда не попадает: платформа переставляет напоминание сама, и
 * приложению об этом знать незачем.
 */
export interface ReminderAction {
  kind: 'open' | 'taken'
  /** Приём: «08:00». */
  slot: string
  /** Начало суток этого приёма. */
  day: number
  /** Чьё уведомление — идентификатор человека. Пусто у одиночного дневника. */
  person?: string
}

export type ReminderPermission = 'granted' | 'denied' | 'prompt'

export interface ReminderHealth {
  /** Сколько напоминаний действительно стоит в системе. */
  scheduled: number
  /** До какого момента расставлено. `null` — не расставлено ничего. */
  until: number | null
  /** Канал уведомлений выключен человеком в настройках телефона. */
  channelOff: boolean
}

/** Мелодия напоминания. `id` совпадает с именем файла в ресурсах Android. */
export interface ReminderSound {
  id: string
  name: string
  /** Чем этот звук отличается на слух — человеку выбирать по описанию, не по имени. */
  hint: string
}

/**
 * Напоминания, которые приходят сами, когда приложение закрыто.
 *
 * Ради этого и затевался переезд на нативную версию: браузер разбудить
 * страницу по расписанию не может, и до сих пор напоминания уезжали в
 * календарь телефона. Отдельный порт, потому что платформы здесь расходятся
 * принципиально, а не в мелочах: в вебе такой возможности нет вовсе.
 */
export interface RemindersPort {
  /** Умеет ли платформа будить приложение по расписанию сама. */
  isSupported(): boolean
  permission(): Promise<ReminderPermission>
  /** Спросить разрешение. Обязан вызываться из обработчика жеста. */
  requestPermission(): Promise<ReminderPermission>

  /** Мелодии на выбор. Пусто — выбирать не из чего, играет системный звук. */
  sounds(): ReminderSound[]

  /**
   * Показать настоящее пробное напоминание с выбранной мелодией.
   *
   * Именно напоминание, а не проигрывание файла. Звук уведомления идёт своей
   * громкостью, отдельной от музыки, и подчиняется тихому режиму и настройкам
   * канала — проиграв файл плеером, мы дали бы человеку услышать не то, что он
   * услышит в восемь утра. Заодно это проверяет всю цепочку целиком.
   */
  preview(soundId: string): Promise<boolean>

  /**
   * Переписать весь набор целиком, а не добавить к существующему.
   *
   * Расписание приёма меняется правкой аптечки, и вести разницу между «что
   * стояло» и «что должно стоять» — источник призрачных напоминаний о давно
   * отменённом препарате. Дешевле и надёжнее каждый раз ставить заново.
   */
  schedule(reminders: Reminder[], soundId: string): Promise<void>
  cancelAll(): Promise<void>

  /**
   * Что на самом деле происходит с напоминаниями в системе.
   *
   * Приложение не вправе утверждать «напоминания включены», не спросив об этом
   * систему. Канал уведомлений человек может выключить одним движением из
   * шторки — приложение об этом не узнает и продолжит уверять, что всё
   * работает. Горизонт тоже конечен и истекает беззвучно.
   */
  health(soundId: string): Promise<ReminderHealth>

  /**
   * Подписаться на нажатия по уведомлению и его кнопкам.
   *
   * Возвращает отписку. Обработчик может сработать и при холодном запуске:
   * человек нажал «Принял» на заблокированном экране, приложение при этом было
   * закрыто — система запускает его и отдаёт событие.
   */
  onAction(handler: (action: ReminderAction) => void): () => void

  /** Открыть системный экран, где меняются громкость и вибрация. */
  openSoundSettings(soundId: string): Promise<boolean>

  /**
   * Разрешено ли системой ставить напоминания на точное время.
   *
   * Измерено на живом телефоне: без этого разрешения система выдаёт будильник
   * с окном, которое растёт со временем — десять минут на ближайшее
   * напоминание, двадцать две на следующее. «Принять в восемь» превращается в
   * «где-то между восемью и половиной девятого», а повторы через пятнадцать
   * минут слипаются.
   *
   * `null` — вопрос к платформе неприменим.
   */
  exactTiming(): Promise<boolean | null>

  /** Открыть системный экран, где это разрешение выдаётся. */
  requestExactTiming(): Promise<boolean | null>

  /**
   * Включён ли сейчас режим «Не беспокоить».
   *
   * В нём уведомление приходит молча, а беззвучное напоминание о лекарстве
   * равно отсутствующему. `null` — платформа не отвечает.
   */
  isQuietModeOn(): Promise<boolean | null>

  /**
   * Разрешено ли напоминанию звучать в тихом режиме.
   *
   * Систему об этом просит человек отдельно: обход «Не беспокоить» доступен
   * только приложениям, которым выдан доступ к политике уведомлений. Не выдан —
   * напоминание приходит молча, и приложение обязано сказать об этом прямо, а
   * не делать вид, что всё работает.
   */
  canBypassQuietMode(): Promise<boolean | null>
  /** Открыть системный экран, где этот доступ выдаётся. */
  requestQuietModeBypass(): Promise<boolean>

  /**
   * Стоит ли на приложении системное ограничение энергосбережения.
   *
   * Нужно, чтобы не пугать предупреждением того, у кого всё в порядке:
   * предупреждение, которое висит всегда, перестают читать, и в тот день,
   * когда оно окажется правдой, его не заметят.
   *
   * Ответ неполный, и это надо помнить. Система отвечает про свой список
   * исключений, а у Huawei, Xiaomi и Samsung поверх него есть собственное
   * управление запуском приложений, о котором Android ничего не знает. Поэтому
   * `false` значит «системных ограничений нет», а не «напоминания точно
   * придут». `null` — платформа не ответила.
   */
  isBatteryRestricted(): Promise<boolean | null>

  /** Открыть системный список «Батарея — приложения без ограничений». */
  openBatterySettings(): Promise<boolean>
}

