/**
 * Оценка без подписи — это оценка приложения.
 *
 * Приложение показывает категорию давления, оценку сахара и рекомендации при
 * крайних значениях. Каждое такое место обязано говорить, чьё это суждение:
 * шкала ESC/ESH, целевые значения самого человека, общая рекомендация. Иначе
 * получается, что судит приложение, а это уже не дневник (`BACKLOG.md` §11,
 * письмо Росздравнадзора 02И-297/20).
 *
 * Проверка разбирает исходники, потому что стережёт она не логику, а привычку:
 * новый экран с плашкой категории заводится за пять минут, и подпись к нему
 * забывается ровно так же быстро.
 */
import { readFileSync, readdirSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const здесь = fileURLToPath(import.meta.url)
const root = join(здесь.slice(0, здесь.lastIndexOf('/')), '..')

/** Что считается показанным суждением. */
const СУЖДЕНИЯ = [
  { имя: 'совет при крайнем значении', как: /\balertFor\(|\bglucoseAlertFor\(/ },
  { имя: 'плашка категории', как: /<CategoryBadge/ },
  { имя: 'название категории', как: /classify(Glucose)?\([^)]*\)\.label|preview\.label|category\.label/ },
]

/**
 * Экраны, которым подпись не нужна, и почему. Список короткий намеренно: он
 * растёт только вместе с объяснением.
 */
const ИСКЛЮЧЕНИЯ = {
  'Report.tsx': 'у отчёта своя развёрнутая сноска «Как получены данные» — там и шкала, и цели названы полностью',
  'bits.tsx': 'сама плашка, а не экран: подпись ставится там, где плашку показывают',
}

export function run() {
  let failures = 0
  const check = (name, condition, detail = '') => {
    if (condition) console.log(`  ok   ${name}`)
    else {
      console.log(`  FAIL ${name}${detail ? ' — ' + detail : ''}`)
      failures++
    }
  }

  const каталог = join(root, 'src/ui')
  const файлы = readdirSync(каталог).filter((f) => f.endsWith('.tsx'))

  const безПодписи = []
  let сСуждением = 0
  for (const имя of файлы) {
    const текст = readFileSync(join(каталог, имя), 'utf8')
    const найдено = СУЖДЕНИЯ.filter((s) => s.как.test(текст))
    if (найдено.length === 0) continue
    сСуждением += 1
    if (ИСКЛЮЧЕНИЯ[имя]) continue
    if (!/from '\.\.\/logic\/disclaimer'/.test(текст)) {
      безПодписи.push(`${имя} (${найдено.map((s) => s.имя).join(', ')})`)
    }
  }

  // Без этой проверки молчание означало бы «разбор перестал узнавать суждения»,
  // а не «все подписаны».
  check('экраны с оценками нашлись', сСуждением >= 4, `нашлось ${сСуждением}`)
  check('у каждой оценки названа её шкала или источник', безПодписи.length === 0, безПодписи.join(' | '))

  // Сами тексты: без них подпись превращается в пустую строку.
  const оговорки = readFileSync(join(root, 'src/logic/disclaimer.ts'), 'utf8')
  check('шкала давления названа по имени', /ESC\/ESH/.test(оговорки))
  check('совет назван общим, а не назначением', /не назначение/.test(оговорки))
  check('сказано, что диагноза приложение не ставит', /не ставит диагноз/.test(оговорки))

  // Назначение обязано стоять и на первом запуске, и в «О приложении»: человек
  // должен узнать, с чем имеет дело, до того как начнёт вносить давление.
  for (const экран of ['Onboarding.tsx', 'About.tsx']) {
    check(
      `назначение сказано на «${экран.replace('.tsx', '')}»`,
      /PURPOSE/.test(readFileSync(join(каталог, экран), 'utf8')),
    )
  }

  return failures
}
