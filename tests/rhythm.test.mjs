/**
 * Ритм приёма: не каждый день.
 *
 * Проверяется не только арифметика окон, но и то, ради чего всё затевалось:
 * расход усредняется по ритму, напоминания молчат в выходные дни цикла, а
 * препарат с законченным курсом не зовёт себя принять (на этом приложение
 * ошибалось до появления ритма — дефект нашёлся здесь же).
 */
import {
  normalizeRhythm, intakeOn, rhythmDuty, nextIntakeDays, shiftRhythm,
  describeRhythm, describeUpcoming, isoWeekday,
  dosesOn, perDayOf, supplyDays, buildReminders, buildCalendar, buildMemo, perTimeOf,
} from './build/api.mjs'

const ДЕНЬ = 24 * 60 * 60 * 1000
const дата = (г, м, д) => new Date(г, м, д).getTime()

/** Понедельник 7 сентября 2026 — от него считаются все дни недели ниже. */
const ПОНЕДЕЛЬНИК = дата(2026, 8, 7)

const препарат = (fields) => ({
  id: 'r1', name: 'Пробный', dose: '', left: null, perDay: null, expires: null, ...fields,
})

export function run() {
  let failures = 0
  const check = (name, condition, detail = '') => {
    if (condition) console.log(`  ok   ${name}`)
    else {
      console.log(`  FAIL ${name}${detail ? ' — ' + detail : ''}`)
      failures++
    }
  }

  // ── что считается ритмом ────────────────────────────────────────────────
  check('понедельник опознан первым днём недели', isoWeekday(ПОНЕДЕЛЬНИК) === 1)
  check('воскресенье седьмое, а не нулевое', isoWeekday(ПОНЕДЕЛЬНИК + 6 * ДЕНЬ) === 7)

  check('пусто — это каждый день', normalizeRhythm(undefined) === undefined)
  check('все семь дней недели — это каждый день', normalizeRhythm({ weekdays: [1, 2, 3, 4, 5, 6, 7] }) === undefined)
  check('цикл без перерыва — это каждый день', normalizeRhythm({ onDays: 3, offDays: 0 }) === undefined)
  check('дробный цикл отброшен', normalizeRhythm({ onDays: 1.5, offDays: 0.5 }) === undefined)
  check('отрицательный цикл отброшен', normalizeRhythm({ onDays: -1, offDays: 2 }) === undefined)
  check('чужие номера дней недели выброшены', JSON.stringify(normalizeRhythm({ weekdays: [0, 3, 9, 3] })?.weekdays) === '[3]')
  check(
    'дни недели старше цикла',
    normalizeRhythm({ weekdays: [1], onDays: 5, offDays: 2 })?.onDays === undefined,
  )

  // ── какие дни приёмные ──────────────────────────────────────────────────
  const черезДень = { onDays: 1, offDays: 1, from: ПОНЕДЕЛЬНИК }
  check('через день: понедельник приёмный', intakeOn(черезДень, ПОНЕДЕЛЬНИК))
  check('через день: вторник пропускаем', !intakeOn(черезДень, ПОНЕДЕЛЬНИК + ДЕНЬ))
  check('через день: среда приёмная', intakeOn(черезДень, ПОНЕДЕЛЬНИК + 2 * ДЕНЬ))
  check('через день: правило действует и назад', !intakeOn(черезДень, ПОНЕДЕЛЬНИК - ДЕНЬ))

  const черезДва = { onDays: 1, offDays: 2, from: ПОНЕДЕЛЬНИК }
  check(
    'через 2 дня: понедельник и четверг, между ними пусто',
    intakeOn(черезДва, ПОНЕДЕЛЬНИК) &&
      !intakeOn(черезДва, ПОНЕДЕЛЬНИК + ДЕНЬ) &&
      !intakeOn(черезДва, ПОНЕДЕЛЬНИК + 2 * ДЕНЬ) &&
      intakeOn(черезДва, ПОНЕДЕЛЬНИК + 3 * ДЕНЬ),
  )

  const пятьЧерезДва = { onDays: 5, offDays: 2, from: ПОНЕДЕЛЬНИК }
  const неделя = Array.from({ length: 7 }, (_, i) => intakeOn(пятьЧерезДва, ПОНЕДЕЛЬНИК + i * ДЕНЬ))
  check('цикл 5 через 2: пять подряд, потом два пустых', JSON.stringify(неделя) === JSON.stringify([true, true, true, true, true, false, false]))
  check('цикл 5 через 2: на восьмой день начинается заново', intakeOn(пятьЧерезДва, ПОНЕДЕЛЬНИК + 7 * ДЕНЬ))

  const поДням = { weekdays: [1, 4] }
  check(
    'по дням недели: понедельник и четверг',
    intakeOn(поДням, ПОНЕДЕЛЬНИК) && intakeOn(поДням, ПОНЕДЕЛЬНИК + 3 * ДЕНЬ) && !intakeOn(поДням, ПОНЕДЕЛЬНИК + ДЕНЬ),
  )
  check('по дням недели: через неделю те же дни', intakeOn(поДням, ПОНЕДЕЛЬНИК + 7 * ДЕНЬ))
  check('без ритма приёмный любой день', intakeOn(undefined, ПОНЕДЕЛЬНИК + 3 * ДЕНЬ))

  // ── сдвиг фазы ──────────────────────────────────────────────────────────
  const сдвинутый = shiftRhythm(черезДень, 1)
  check('сдвиг на день меняет приёмные дни местами', !intakeOn(сдвинутый, ПОНЕДЕЛЬНИК) && intakeOn(сдвинутый, ПОНЕДЕЛЬНИК + ДЕНЬ))
  const дважды = shiftRhythm(сдвинутый, 1)
  check('два сдвига у «через день» возвращают исходное', intakeOn(дважды, ПОНЕДЕЛЬНИК))
  check('дни недели сдвигать нечего — они привязаны к календарю', JSON.stringify(shiftRhythm(поДням, 1)) === JSON.stringify(поДням))

  // ── доля приёмных дней ──────────────────────────────────────────────────
  check('без ритма расходуется каждый день', rhythmDuty(undefined) === 1)
  check('через день — половина', rhythmDuty(черезДень) === 0.5)
  check('через 2 дня — треть', Math.abs(rhythmDuty(черезДва) - 1 / 3) < 1e-9)
  check('пять через два — пять седьмых', Math.abs(rhythmDuty(пятьЧерезДва) - 5 / 7) < 1e-9)
  check('два дня недели — две седьмых', Math.abs(rhythmDuty(поДням) - 2 / 7) < 1e-9)

  // ── ближайшие дни ───────────────────────────────────────────────────────
  const ближайшие = nextIntakeDays(черезДень, ПОНЕДЕЛЬНИК, 3)
  check('ближайшие три приёма идут через день', JSON.stringify(ближайшие) === JSON.stringify([ПОНЕДЕЛЬНИК, ПОНЕДЕЛЬНИК + 2 * ДЕНЬ, ПОНЕДЕЛЬНИК + 4 * ДЕНЬ]))
  check('без ритма ближайшие идут подряд', nextIntakeDays(undefined, ПОНЕДЕЛЬНИК, 2)[1] === ПОНЕДЕЛЬНИК + ДЕНЬ)
  check('поиск не зависает на редком ритме', nextIntakeDays({ onDays: 1, offDays: 300 }, ПОНЕДЕЛЬНИК, 3).length >= 1)

  // ── слова ───────────────────────────────────────────────────────────────
  check('каждый день словами не описывается', describeRhythm(undefined) === null)
  check('«через день»', describeRhythm(черезДень) === 'через день')
  check('«через 2 дня»', describeRhythm(черезДва) === 'через 2 дня', describeRhythm(черезДва))
  check('цикл словами', describeRhythm(пятьЧерезДва) === '5 дней приёма, 2 дня перерыва', describeRhythm(пятьЧерезДва))
  check('два дня недели — полными именами', describeRhythm(поДням) === 'по понедельникам и четвергам', describeRhythm(поДням))
  check(
    'пять дней недели — сокращениями, иначе строка длиннее экрана',
    describeRhythm({ weekdays: [1, 2, 3, 4, 5] }) === 'по пн, вт, ср, чт и пт',
    describeRhythm({ weekdays: [1, 2, 3, 4, 5] }),
  )

  const сегодня = ПОНЕДЕЛЬНИК
  check(
    'ближайшие приёмы названы датами, а не правилом',
    describeUpcoming(черезДень, сегодня) === 'Ближайшие приёмы: сегодня, 9 сентября и 11 сентября',
    describeUpcoming(черезДень, сегодня),
  )
  check(
    'у цикла показан отрезок и когда перерыв кончится',
    describeUpcoming(пятьЧерезДва, сегодня) === 'Приём сегодня — 11 сентября, потом перерыв до 14 сентября',
    describeUpcoming(пятьЧерезДва, сегодня),
  )

  // ── что из этого следует в аптечке ──────────────────────────────────────
  const ежедневный = препарат({ times: ['08:00'], perTime: 1, left: 30, leftAt: ПОНЕДЕЛЬНИК, since: ПОНЕДЕЛЬНИК })
  const черезДеньПрепарат = { ...ежедневный, rhythm: черезДень }

  check('в приёмный день приём есть', dosesOn(черезДеньПрепарат, ПОНЕДЕЛЬНИК, ПОНЕДЕЛЬНИК).length === 1)
  check('в выходной день ритма приёмов нет', dosesOn(черезДеньПрепарат, ПОНЕДЕЛЬНИК + ДЕНЬ, ПОНЕДЕЛЬНИК).length === 0)

  check('расход ежедневного — штука в сутки', perDayOf(ежедневный) === 1)
  check('расход через день — половина штуки в сутки', perDayOf(черезДеньПрепарат) === 0.5)
  check(
    'тридцати таблеток через день хватает вдвое дольше',
    supplyDays(ежедневный) === 30 && supplyDays(черезДеньПрепарат) === 60,
    `${supplyDays(ежедневный)} и ${supplyDays(черезДеньПрепарат)}`,
  )

  // ── напоминания ─────────────────────────────────────────────────────────
  const набор = buildReminders([черезДеньПрепарат], ПОНЕДЕЛЬНИК, { repeat: false, horizonDays: 4 })
  const дниНабора = набор.map((r) => new Date(r.at).getDate())
  check('напоминания встают только в приёмные дни', JSON.stringify(дниНабора) === JSON.stringify([7, 9]), JSON.stringify(дниНабора))

  check(
    'ежедневный препарат напоминания получает',
    buildReminders([ежедневный], ПОНЕДЕЛЬНИК, { repeat: false, horizonDays: 4 }).length === 4,
  )

  // Дефект, который нашёлся при этой работе: курс кончился, а напоминания шли.
  const законченный = препарат({
    times: ['08:00'], perTime: 1, since: ПОНЕДЕЛЬНИК - 10 * ДЕНЬ,
    planFrom: ПОНЕДЕЛЬНИК - 10 * ДЕНЬ, plan: [{ perTime: 1, days: 5 }],
  })
  check('законченный курс себя принять не зовёт', buildReminders([законченный], ПОНЕДЕЛЬНИК, { repeat: false }).length === 0)

  // ── памятка на холодильник ──────────────────────────────────────────────
  {
    const слоты = [{ time: '08:00', title: 'Утро' }]
    const памятка = buildMemo([{ ...черезДеньПрепарат, name: 'Через день' }], слоты, ПОНЕДЕЛЬНИК)
    const приём = памятка.slots[0]
    check('в памятке ритм подписан у препарата', приём.items[0].rhythm === 'через день', String(приём.items[0].rhythm))
    check(
      'клетки чередуются: рабочая, перерыв, рабочая',
      JSON.stringify(приём.days) === JSON.stringify([true, false, true, false, true, false, true]),
      JSON.stringify(приём.days),
    )
    check('на неделю отсчитывается четыре штуки, а не семь', памятка.totals[0].pieces === 4, String(памятка.totals[0]?.pieces))

    const ежедневнаяПамятка = buildMemo([ежедневный], слоты, ПОНЕДЕЛЬНИК)
    check('у ежедневного все клетки рабочие', ежедневнаяПамятка.slots[0].days.every(Boolean))
    check('и на неделю отсчитывается семь', ежедневнаяПамятка.totals[0].pieces === 7)
  }

  // ── выгрузка в календарь ────────────────────────────────────────────────
  {
    const ics = (m) => buildCalendar([m], ПОНЕДЕЛЬНИК)
    check('ежедневный уходит простым правилом', ics(ежедневный).includes('RRULE:FREQ=DAILY\r\n'))
    check('через день — правило с шагом два', ics(черезДеньПрепарат).includes('RRULE:FREQ=DAILY;INTERVAL=2'), '')
    check(
      'дни недели — недельное правило с их кодами',
      ics({ ...ежедневный, rhythm: поДням }).includes('RRULE:FREQ=WEEKLY;BYDAY=MO,TH'),
    )
    // Цикл «5 через 2» простым правилом не выражается — даты перечисляются.
    const цикл = ics({ ...ежедневный, rhythm: пятьЧерезДва })
    check('цикл выгружается перечислением дат', цикл.includes('RDATE;VALUE=DATE-TIME:') && !цикл.includes('RRULE'), '')
    check('и дат в нём не одна', (цикл.match(/T\d{6}/g) ?? []).length > 10)
  }

  // ── ритм и схема с меняющейся дозой живут порознь ───────────────────────
  // «Неделю по половине, потом по целой» врач считает календарными днями, а не
  // приёмами: при приёме через день неделя всё равно кончается на седьмой день.
  // Правило неочевидное, поэтому закреплено здесь.
  {
    const сХемой = препарат({
      times: ['08:00'], since: ПОНЕДЕЛЬНИК, planFrom: ПОНЕДЕЛЬНИК,
      plan: [{ perTime: 0.5, days: 7 }, { perTime: 1, days: null }],
      rhythm: черезДень,
    })
    check('на седьмой день ещё половина', perTimeOf(сХемой, ПОНЕДЕЛЬНИК + 6 * ДЕНЬ) === 0.5)
    check('на восьмой — уже целая, хотя приёмов было четыре', perTimeOf(сХемой, ПОНЕДЕЛЬНИК + 7 * ДЕНЬ) === 1)
    check('и в выходной день ритма приёма всё равно нет', dosesOn(сХемой, ПОНЕДЕЛЬНИК + 7 * ДЕНЬ, ПОНЕДЕЛЬНИК).length === 0)
  }

  return failures
}
