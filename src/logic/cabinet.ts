/**
 * Правила по словам — когда таблица веществ не помогает.
 *
 * У бинта и пластыря вещества нет вовсе: в реестре лекарств их не найти, и
 * `inn` у них пустой. У добавок наоборот — поле заполнено, но составом в
 * родительном падеже («витаминов группы В»), и ни одно имя вещества в него не
 * попадает. Поэтому правила проверяются по названию и составу вместе.
 *
 * `\b` здесь не годится: в JavaScript граница слова определена через `\w`, а
 * это только латиница с цифрами. `\bбинт` не совпадает с «бинт» никогда — «б»
 * сама по себе не словесный символ, и границы перед ней не возникает.
 * `normalize` уже свёл строку к словам через пробел, поэтому хватает `^` и
 * пробела.
 */
const ПО_СЛОВАМ: [RegExp, string][] = [
  // «Витамин D3», «витаминов группы В» — так пишут и на упаковке добавки, и в
  // реестре свидетельств: там вместо вещества стоит состав в родительном
  // падеже, и ни одно из имён из таблицы веществ в него не попадает.
  [/(?:^|\s)витамин/, 'Витамины'],
  [/(?:^|\s)хондро/, 'Суставы'],
  [/(?:^|\s)(бинт|пластыр|вата|салфетк|жгут|шприц|повязк|марл)/, 'Перевязка'],
  // «йод» — целым словом: иначе «Йодомарин» (калия йодид, добавка для
  // щитовидной железы) попадал бы в перевязочное.
  [/(?:^|\s)(перекис|хлоргексидин|мирамистин|зеленк|бриллиантов)/, 'Перевязка'],
  [/(?:^|\s)йод(?![а-я])/, 'Перевязка'],
]

/**
 * Что предложить в поле категории.
 *
 * `null` — предложить нечего, и это обычный случай: таблица знает малую часть
 * аптеки. Пустое поле честнее выдуманной полки.
 */
export function suggestPurpose(box: Pick<Medicine, 'name' | 'inn'>): string | null {
  const найденные: string[] = []
  for (const вещество of substances(box.inn)) {
    /*
     * Сравниваем по началу, а не точным совпадением.
     *
     * В реестре вещество пишут полным именем соли: «периндоприла эрбумин»,
     * «тиамина хлорид», «амлодипина безилат». Точный ключ не нашёлся бы ни
     * разу — а это как раз то, что подставляется из справочника само.
     *
     * Из совпавших берём самый длинный: если в таблице когда-нибудь окажутся
     * и общее вещество, и его частный случай, выиграет частный, а не тот, что
     * попался в переборе первым.
     */
    let лучший = ''
    for (const ключ of Object.keys(ПО_ВЕЩЕСТВУ)) {
      if (вещество.startsWith(ключ) && ключ.length > лучший.length) лучший = ключ
    }
    if (лучший) найденные.push(ПО_ВЕЩЕСТВУ[лучший])
  }
  /*
   * В комбинации витамины уступают.
   *
   * Аскорбиновая кислота стоит добавкой в половине простудных порошков, и по
   * ней «Аспирин-С» оказывался витаминами. Витамином препарат делает не
   * наличие витамина в составе, а его отсутствие всего остального.
   */
  const главное = найденные.find((к) => к !== 'Витамины') ?? найденные[0]
  if (главное) return главное

  /*
   * Название как вещество — когда вещества нет.
   *
   * У дженериков название и есть вещество: «Аторвастатин», «Метформин»,
   * «Амлодипин». Поле `inn` у них заполняется из реестра, но в аптечке
   * владельца половина коробок заведена руками, и там оно пустое. Пробовать
   * стоит только когда по веществу не нашлось: реестр точнее.
   */
  const имя = normalize(box.name)
  const первоеСлово = имя.split(' ')[0]
  let поИмени = ''
  for (const ключ of Object.keys(ПО_ВЕЩЕСТВУ)) {
    if (первоеСлово.startsWith(ключ) && ключ.length > поИмени.length) поИмени = ключ
  }
  if (поИмени) return ПО_ВЕЩЕСТВУ[поИмени]

  const слова = `${имя} ${normalize(box.inn ?? '')}`.trim()
  for (const [правило, категория] of ПО_СЛОВАМ) if (правило.test(слова)) return категория
  return null
}

/**
 * Какие категории вообще есть в этой аптечке — из них строится фильтр.
 *
 * Не весь список подсказок: фильтр, половина кнопок которого всегда пуста, —
 * это шум. Одинаковые по сути слова схлопываются («Давление» и «давление»), и
 * остаётся написание первой встреченной коробки: это то, что человек набрал
 * сам, и переучивать его не нужно.
 */
export function purposesOf(items: Stock[]): string[] {
  const виденные = new Map<string, string>()
  for (const { box } of items) {
    const своё = (box.purpose ?? '').trim()
    if (!своё) continue
    const ключ = normalize(своё)
    if (!виденные.has(ключ)) виденные.set(ключ, своё)
  }
  return [...виденные.values()].sort((a, b) => a.localeCompare(b, 'ru'))
}

/** Коробки этой категории. Сравнение по нормализованному виду, как в `purposesOf`. */
export function byPurpose(items: Stock[], purpose: string): Stock[] {
  const ключ = normalize(purpose)
  return items.filter(({ box }) => normalize((box.purpose ?? '').trim()) === ключ)
}
