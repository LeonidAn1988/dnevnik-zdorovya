/**
 * Кнопка «Назад» и глубина экранов.
 *
 * Порт понадобился потому, что «назад» на Android и в браузере — принципиально
 * разные вещи. В браузере это история страницы, и приложение обязано её вести,
 * иначе системная кнопка в установленном PWA закроет его из середины настроек.
 * На Android истории у приложения нет и быть не должно: пока подписан слушатель
 * `backButton`, WebView сам назад не ходит (см. `AppPlugin.java`), а `canGoBack`
 * — это состояние списка навигации WebView, которым приложение не управляет.
 * Строить на нём возврат нельзя: одна внешняя ссылка без `target="_blank"`
 * сделает его истинным, и «Назад» на корне уведёт человека с приложения.
 */
export interface NavPort {
  /**
   * Подписать обработчик системного «назад». Обработчик возвращает `true`,
   * если уровень снят, и `false`, если снимать нечего.
   *
   * Слот один, не список: накопить подписки при перерисовке нельзя по
   * построению, иначе одно нажатие снимало бы три уровня разом.
   */
  onBack(handler: () => boolean): () => void

  /** Глубина изменилась. Веб зеркалит её в историю, Android не делает ничего. */
  sync(depth: number): void

  /** «Назад» изнутри приложения — экранная кнопка «К настройкам». */
  back(): void
}

export interface Platform {
  /** Обмен через Яндекс.Диск. */
  cloud: CloudPort
  /**
   * Где приложение выполняется — сайтом в браузере или приложением на телефоне.
   *
   * Нужно интерфейсу и только ему, для формулировок. «Записи есть только в этом
   * браузере», «добавьте на домашний экран», «очистка истории браузера их
   * удалит» — в установленном приложении всё это неправда и сбивает с толку, а
   * правда там другая: данные исчезают при «Очистить данные» и при удалении
   * приложения.
   *
   * Ядру это поле не нужно и не должно понадобиться: любое поведение,
   * зависящее от платформы, обязано жить за портами, а не за проверкой вида.
   */
  kind: 'web' | 'native'

  bluetooth: BluetoothPort
  storage: StoragePort
  files: FilePort
  backup: BackupPort
  reminders: RemindersPort
  nav: NavPort
}

let current: Platform | null = null

export function installPlatform(platform: Platform) {
  current = platform
}

export function platform(): Platform {
  if (!current) {
    throw new Error('Платформа не установлена: вызовите installPlatform() до обращения к портам')
  }
  return current
}
