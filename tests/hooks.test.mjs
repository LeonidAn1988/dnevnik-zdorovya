/**
 * Хуки React обязаны стоять до первого раннего возврата.
 *
 * Правило самих React, а не вкусовое: число вызовов `use*` должно совпадать от
 * отрисовки к отрисовке. Экран, который при одном состоянии возвращает форму, а
 * при другом доходит до `useMemo` ниже, роняет приложение в белый экран с
 * «Rendered fewer hooks than expected».
 *
 * В этом проекте так ломались уже дважды: пустой список покупок в `Restock` и
 * поиск по аптечке. Оба раза дефект ловился не тестами, а обходом экранов в
 * браузере — то есть поздно и только если обход дойдёт до нужной развилки.
 *
 * Проверка разбирает исходники, а не запускает React: без AST она несовершенна
 * и умышленно осторожна — ищет только то, в чём уверена, и молчит там, где не
 * уверена. Ложная тревога здесь дороже пропуска: она заставит переписывать
 * здоровый код.
 */
import { readFileSync, readdirSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const здесь = fileURLToPath(import.meta.url)
const root = join(здесь.slice(0, здесь.lastIndexOf('/')), '..')

/** Начало компонента верхнего уровня: `function Имя(` или `export function Имя(`. */
const НАЧАЛО = /^(export )?function [A-ZА-Я]/

/**
 * Ранний возврат верхнего уровня тела компонента.
 *
 * Только с двумя пробелами отступа: вложенные `if` внутри обработчиков и циклов
 * на порядок хуков не влияют, а отличить их без AST нельзя.
 */
const ЕСЛИ_ОДНОЙ_СТРОКОЙ = /^ {2}if \(.*\) return/
const ЕСЛИ_БЛОКОМ = /^ {2}if \(.*\{\s*$/
const ВОЗВРАТ_В_БЛОКЕ = /^ {4}return /m

/** Вызов хука на верхнем уровне тела: `const x = useMemo(`, `useEffect(`. */
const ХУК = /^ {2}(const |let |)?[^/*]*\buse[A-Z]\w*\(/

/** Разрезать файл на компоненты: от одного `function Имя(` до следующего. */
function компоненты(строки) {
  const границы = строки.map((l, i) => (НАЧАЛО.test(l) ? i : -1)).filter((i) => i >= 0)
  границы.push(строки.length)
  const части = []
  for (let i = 0; i < границы.length - 1; i += 1) {
    части.push({ сдвиг: границы[i], тело: строки.slice(границы[i], границы[i + 1]) })
  }
  return части
}

export function run() {
  let failures = 0
  const check = (name, condition, detail = '') => {
    if (condition) console.log(`  ok   ${name}`)
    else {
      console.log(`  FAIL ${name}${detail ? ' — ' + detail : ''}`)
      failures++
    }
  }

  const каталог = join(root, 'src/ui')
  const файлы = readdirSync(каталог).filter((f) => f.endsWith('.tsx'))
  check('экраны нашлись', файлы.length > 10, String(файлы.length))

  const нарушения = []
  let сРанним = 0
  for (const имя of файлы) {
    const строки = readFileSync(join(каталог, имя), 'utf8').split('\n')
    for (const { сдвиг, тело } of компоненты(строки)) {
      let ранний = -1
      for (let i = 0; i < тело.length; i += 1) {
        const l = тело[i]
        const блоком = ЕСЛИ_БЛОКОМ.test(l) && ВОЗВРАТ_В_БЛОКЕ.test(тело.slice(i, i + 30).join('\n'))
        if (ЕСЛИ_ОДНОЙ_СТРОКОЙ.test(l) || блоком) {
          ранний = i
          break
        }
      }
      if (ранний === -1) continue
      сРанним += 1
      for (let i = ранний + 1; i < тело.length; i += 1) {
        if (ХУК.test(тело[i])) нарушения.push(`${имя}:${сдвиг + i + 1} — ${тело[i].trim().slice(0, 60)}`)
      }
    }
  }

  // Проверка бессмысленна, если ранних возвратов вообще не нашлось: значит,
  // разбор перестал их узнавать, и молчание означает «не искали».
  check('ранние возвраты в экранах найдены', сРанним >= 5, `нашлось ${сРанним}`)
  check('ни одного хука после раннего возврата', нарушения.length === 0, нарушения.slice(0, 4).join(' | '))

  return failures
}
