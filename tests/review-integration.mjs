    await page.evaluate(async()=>{await window.backup.saveNow();await window.backup.shareNow()})
    await page.waitForTimeout(80)
    assert.deepEqual(await page.evaluate(()=>({at:window.settings.backupLastAt,signature:window.settings.backupLastSignature})),saved)
    assert.equal(await page.evaluate(()=>window.writes.length),1)
    assert.equal(await page.evaluate(()=>window.savedFiles.length+window.sharedFiles.length),0)
    assert.equal(await page.evaluate(()=>window.file.measurements[0].sys),120)
    await page.evaluate(()=>{window.failGraves=false;window.refresh()});await page.waitForFunction(()=>window.writes.length===2)
    await page.evaluate(()=>window.writes[1].complete());await page.waitForFunction(()=>!window.backup.stalled)
    assert.equal(await page.evaluate(()=>window.file.measurements[0].sys),130)
    assert.equal(await page.evaluate(()=>window.file.tombstones[0].id),'new-grave')
    // Даже при свежем кэше ручной файл требует отдельного успешного чтения.
