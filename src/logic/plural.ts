/**
 * Русские окончания для счётного существительного: «1 запись», «2 записи»,
 * «5 записей». Библиотеку локализации ради одного правила не тянем, а без него
 * интерфейс выдаёт «5 препарата» — мелочь, но именно по таким мелочам видно,
 * что текст писали не для людей.
 */
export function plural(n: number, one: string, few: string, many: string): string {
  const mod100 = Math.abs(n) % 100
  if (mod100 >= 11 && mod100 <= 14) return many
  const mod10 = mod100 % 10
  if (mod10 === 1) return one
  if (mod10 >= 2 && mod10 <= 4) return few
  return many
}

/**
 * Месяц и год в родительном падеже: «июля 2025».
 *
 * `Intl` с `{ month: 'long' }` даёт именительный — «июль 2025 г.», и во фразе
 * «принимает с июль 2025 г.» это читается как ошибка, а стоит она в документе,
 * который человек несёт врачу. Форматтер с днём падеж даёт верный, но тогда в
 * строке появляется выдуманное число: месяц человек называет, а день начала
 * приёма не помнит никто.
 */
const МЕСЯЦЫ = [
  'января', 'февраля', 'марта', 'апреля', 'мая', 'июня',
  'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря',
]

export function monthYear(ts: number): string {
  const d = new Date(ts)
  return `${МЕСЯЦЫ[d.getMonth()]} ${d.getFullYear()}`
}

/**
 * Дробное число по-русски: с запятой.
 *
 * `toFixed` даёт точку, и одно и то же значение уходило врачу как «6,2», а на
 * экране показывалось как «6.2». Во вводе запятая уже была — расходились
 * только показ и печать.
 */
export function десятичное(value: number, знаков = 1): string {
  return value.toFixed(знаков).replace('.', ',')
}
