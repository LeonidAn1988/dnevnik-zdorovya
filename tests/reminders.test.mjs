/**
 * Сборка напоминаний о приёме.
 *
 * Проверяется то, из-за чего напоминание молчит, врёт или не замолкает:
 * слипание препаратов по времени, повторы до отметки, снятие повторов уже
 * отмеченного приёма, прошедшие моменты и устойчивость идентификаторов.
 */
import { execFileSync } from 'node:child_process'
import {
  soundScreenHint,
  HORIZON_DAYS,
  MAX_REMINDERS,
  REPEATS,
  REPEAT_INTERVAL_MIN,
  buildReminders as _buildReminders,
  doseLine as _doseLine,
  reminderId,
  medicinesForReminder as _medicinesForReminder,
  reminderTimes as _reminderTimes,
  splitBox,
  dosing,
  shortBody,
  MAX_PEOPLE,
} from './build/api.mjs'


/*
 * Фикстуры плоские — препарат одним объектом, как до 0.27.0. Раскладывает их
 * тот же `splitBox`, что и обновление базы: здесь проверяются напоминания, а не
 * способ хранения. Человек берётся из `owner` фикстуры и становится `person`
 * курса — ровно так же, как при переносе настоящего дневника.
 */
const вПриёмы = (list) =>
  list.map((m) => {
    const { box, regimen } = splitBox(m, m.owner ?? 'p1')
    return dosing(box, regimen ?? { id: `r-${box.id}`, medicineId: box.id, person: m.owner ?? 'p1' })
  })
const buildReminders = (list, now, opts) => _buildReminders(вПриёмы(list), now, opts)
const medicinesForReminder = (list, people, slot, day, now, person) =>
  _medicinesForReminder(вПриёмы(list), people, slot, day, now, person)
const reminderTimes = (list) => _reminderTimes(вПриёмы(list))
const doseLine = (m, owner, day) => _doseLine(вПриёмы([m])[0], owner, day)

export function run() {
  let failures = 0
  const check = (name, condition, detail = '') => {
    if (condition) console.log(`  ok   ${name}`)
    else {
      console.log(`  FAIL ${name}${detail ? ' — ' + detail : ''}`)
      failures++
    }
  }

  const med = (over) => ({
    id: 'med-1', name: 'Лозартан', dose: '50 мг', left: 30, perDay: null, expires: null, ...over,
  })
  // Шесть утра: приёмы в 08:00 и 20:00 ещё впереди, вчерашние — позади.
  const now = new Date(2026, 7, 20, 6, 0, 0).getTime()
  const начало = (сдвиг = 0) => new Date(2026, 7, 20 + сдвиг, 0, 0, 0).getTime()
  const момент = (час, минута = 0, сдвиг = 0) => new Date(2026, 7, 20 + сдвиг, час, минута, 0).getTime()

  // ── строка препарата ─────────────────────────────────────────────────────
  check('название и дозировка', doseLine(med({})) === 'Лозартан 50 мг')
  check(
    'штуки указываются только когда их больше одной',
    doseLine(med({ perTime: 1 })) === 'Лозартан 50 мг' && doseLine(med({ perTime: 2 })) === 'Лозартан 50 мг — 2 шт.',
  )
  check('отношение к еде попадает в строку', doseLine(med({ meal: 'after' })) === 'Лозартан 50 мг — после еды')
  check('штуки и еда вместе', doseLine(med({ perTime: 2, meal: 'before' })) === 'Лозартан 50 мг — 2 шт., до еды')

  // ── времена приёма ───────────────────────────────────────────────────────
  check('времена собираются без повторов и по порядку', JSON.stringify(reminderTimes([
    med({ id: 'a', times: ['20:00'] }),
    med({ id: 'b', times: ['08:00', '20:00'] }),
  ])) === JSON.stringify(['08:00', '20:00']))
  check('нечитаемое время в список не идёт', JSON.stringify(reminderTimes([med({ times: ['вечером'] })])) === '[]')

  // ── пусто ────────────────────────────────────────────────────────────────
  check('пустая аптечка — пустой набор', buildReminders([], now).length === 0)
  check('препараты без расписания не напоминают', buildReminders([med({ times: [] })], now).length === 0)

  // ── группировка и повторы ────────────────────────────────────────────────
  const один = buildReminders([med({ times: ['08:00'] })], now, { repeat: true, horizonDays: 1 })
  check('один приём даёт основное плюс повторы', один.length === REPEATS + 1, `получилось ${один.length}`)
  check('первое — ровно в назначенное время', один[0].at === момент(8), new Date(один[0].at).toString())
  check(
    'повторы идут через заданный интервал',
    один.every((r, i) => r.at === момент(8) + i * REPEAT_INTERVAL_MIN * 60_000),
  )
  check('шаги пронумерованы подряд', JSON.stringify(один.map((r) => r.step)) === JSON.stringify([0, 1, 2, 3]))
  check('заголовок повтора отличается от основного', один[0].title !== один[1].title, один[1].title)
  check('повтор напоминает по-человечески, без служебных слов', один[1].title === 'Не забудьте: приём в 08:00', один[1].title)

  const без = buildReminders([med({ times: ['08:00'] })], now, { repeat: false, horizonDays: 1 })
  check('без повторов остаётся одно напоминание', без.length === 1)

  const двое = buildReminders(
    [med({ id: 'a', name: 'Метформин', times: ['08:00'] }), med({ id: 'b', name: 'Аторвастатин', times: ['08:00'] })],
    now,
    { repeat: false, horizonDays: 1 },
  )
  check('два препарата на одно время — одно уведомление', двое.length === 1, `получилось ${двое.length}`)
  check('оба препарата в подробностях', двое[0].details.split('\n').length === 2, двое[0].details.replace(/\n/g, ' | '))
  check('препараты внутри уведомления по алфавиту', двое[0].details.startsWith('Аторвастатин'), двое[0].details)


  // ── свёрнутая строка ─────────────────────────────────────────────────────
  check('один препарат — просто название', shortBody(['Метформин']) === 'Метформин')
  check('два — через «и»', shortBody(['Метформин', 'Периндоприл']) === 'Метформин и Периндоприл')
  check(
    'больше двух — с остатком числом',
    shortBody(['Аторвастатин', 'Метформин', 'Периндоприл', 'Лозартан']) === 'Аторвастатин, Метформин и ещё 2',
    shortBody(['Аторвастатин', 'Метформин', 'Периндоприл', 'Лозартан']),
  )
  check('свёрнутая строка помещается в одну строку', !двое[0].body.includes('\n'), двое[0].body)
  check('свёрнутая строка называет оба препарата', двое[0].body === 'Аторвастатин и Метформин', двое[0].body)

  // ── горизонт ─────────────────────────────────────────────────────────────
  const неделя = buildReminders([med({ times: ['08:00'] })], now, { repeat: false, horizonDays: 7 })
  check('горизонт соблюдается', неделя.length === 7, `получилось ${неделя.length}`)
  check('набор отсортирован по времени', неделя.every((r, i) => i === 0 || r.at >= неделя[i - 1].at))
  check('по умолчанию горизонт — две недели', HORIZON_DAYS === 14)

  // ── прошедшее ────────────────────────────────────────────────────────────
  const позже = new Date(2026, 7, 20, 8, 20, 0).getTime()
  const хвост = buildReminders([med({ times: ['08:00'] })], позже, { repeat: true, horizonDays: 1 })
  check(
    'прошедшие моменты не ставятся, оставшиеся повторы — да',
    хвост.length === 2 && хвост.every((r) => r.at > позже),
    `получилось ${хвост.length}`,
  )

  // ── отметка снимает повторы ──────────────────────────────────────────────
  const отмечено = buildReminders(
    [med({ times: ['08:00', '20:00'], taken: [момент(8)] })],
    now,
    { repeat: true, horizonDays: 1 },
  )
  check(
    'отмеченный приём не напоминает вовсе',
    отмечено.every((r) => r.slot === '20:00'),
    отмечено.map((r) => r.slot).join(','),
  )
  check('второй приём того же дня остаётся', отмечено.length === REPEATS + 1, `получилось ${отмечено.length}`)

  const частично = buildReminders(
    [
      med({ id: 'a', name: 'Метформин', times: ['08:00'], taken: [момент(8)] }),
      med({ id: 'b', name: 'Аторвастатин', times: ['08:00'] }),
    ],
    now,
    { repeat: false, horizonDays: 1 },
  )
  check('отмеченный препарат исчезает из текста', частично.length === 1 && частично[0].details === 'Аторвастатин 50 мг',
    частично[0]?.details)

  check(
    'отметка вчера на завтрашние напоминания не влияет',
    buildReminders([med({ times: ['08:00'], taken: [момент(8, 0, -1)] })], now, { repeat: false, horizonDays: 2 })
      .length === 2,
  )


  // ── потолок на число будильников ─────────────────────────────────────────
  //
  // Android держит не больше пятисот ожидающих будильников на приложение и
  // лишние отбрасывает молча. Плотное расписание в потолок упирается.
  {
    const часы = Array.from({ length: 10 }, (_, i) => `${String(6 + i).padStart(2, '0')}:00`)
    const плотно = buildReminders([med({ id: 'a', times: часы })], now, { repeat: true, horizonDays: 14 })
    // Горизонт укорачивается целыми днями, а не обрезкой хвоста: система не
    // выбрасывает произвольную половину, а набор использует почти весь запас.
    check(
      'набор не перерастает системный предел',
      плотно.length <= MAX_REMINDERS && плотно.length > MAX_REMINDERS - 10 * 4,
      `получилось ${плотно.length} при потолке ${MAX_REMINDERS}`,
    )
    check('обрезается хвост, а не начало', плотно[0].at < плотно[плотно.length - 1].at)
    check(
      'ближайшие сутки уцелели полностью',
      плотно.filter((r) => r.day === начало(0)).length > 0,
    )
  }

  // ── идентификаторы ───────────────────────────────────────────────────────
  const много = buildReminders(
    [med({ id: 'a', times: ['08:00', '14:00', '20:00'] })],
    now,
    { repeat: true, horizonDays: 5 },
  )
  check('идентификаторы уникальны', new Set(много.map((r) => r.id)).size === много.length,
    `${много.length} штук, различных ${new Set(много.map((r) => r.id)).size}`)
  check('идентификатор укладывается в 32 бита', много.every((r) => r.id > 0 && r.id < 2 ** 31))
  check(
    'идентификатор восстанавливается из дня, приёма и шага',
    много[0].id === reminderId(начало(0), 0, 0),
  )
  check(
    'переименование препарата идентификаторов не меняет',
    buildReminders([med({ id: 'x', name: 'Другое', times: ['08:00'] })], now, { repeat: false, horizonDays: 1 })[0].id
      === buildReminders([med({ id: 'a', times: ['08:00'] })], now, { repeat: false, horizonDays: 1 })[0].id,
  )

  // ── привязка к приёму ────────────────────────────────────────────────────
  check(
    'сутки у каждого напоминания совпадают с его же моментом',
    много.every((r) => r.day === new Date(r.at).setHours(0, 0, 0, 0)),
    много.map((r) => `${new Date(r.at).toLocaleString('ru')} → ${new Date(r.day).toLocaleDateString('ru')}`).slice(0, 3).join('; '),
  )
  check(
    'приёмы покрывают все времена расписания',
    JSON.stringify([...new Set(много.map((r) => r.slot))].sort()) === JSON.stringify(['08:00', '14:00', '20:00']),
  )
  check('приём записан как в расписании', один.every((r) => r.slot === '08:00'))
  check('сутки — начало дня, а не момент приёма', один.every((r) => r.day === начало(0)))


  // ── перевод часов ────────────────────────────────────────────────────────
  //
  // В Москве часы не переводят с 2014 года, поэтому здесь запускается дочерний
  // процесс в поясе, где переводят. Иначе дефект не воспроизвести: он живёт
  // ровно в тех сутках, которые длятся не двадцать четыре часа.
  //
  // 25 октября 2026 в Берлине сутки длятся 25 часов. Прежний код шагал по
  // горизонту сложением «плюс двадцать четыре часа»: от полуночи 24 октября он
  // давал 24, 25, **25**, 26, 27 — день повторялся, а 28 терялся целиком.
  // Посев именно у полуночи: ближе к полудню лишний час съедается округлением
  // до начала суток, и дефект не воспроизводится.
  {
    const код = `
      const { buildReminders } = await import('${new URL('./build/api.mjs', import.meta.url).href}');
      const med = { id: 'a', name: 'Лозартан', dose: '', left: 30, perDay: null, expires: null, times: ['08:00'] };
      const старт = new Date(2026, 9, 24, 0, 30, 0).getTime();
      const набор = buildReminders([med], старт, { repeat: false, horizonDays: 5 });
      const дни = набор.map((r) => new Date(r.at));
      console.log(JSON.stringify({
        даты: дни.map((d) => d.getDate()),
        часы: dni_hours(дни),
        идентификаторы: набор.map((r) => r.id),
      }));
      function dni_hours(list) { return list.map((d) => d.getHours() * 60 + d.getMinutes()); }
    `
    let итог = null
    try {
      const вывод = execFileSync(process.execPath, ['--input-type=module', '-e', код], {
        env: { ...process.env, TZ: 'Europe/Berlin' },
        encoding: 'utf8',
      })
      итог = JSON.parse(вывод.trim().split('\n').pop())
    } catch (e) {
      итог = { ошибка: String(e && e.message).slice(0, 120) }
    }

    check(
      'горизонт не теряет сутки при переводе часов',
      JSON.stringify(итог.даты) === JSON.stringify([24, 25, 26, 27, 28]),
      `получилось ${JSON.stringify(итог.даты ?? итог)}`,
    )
    check(
      'приём остаётся на 08:00 по местному времени',
      Array.isArray(итог.часы) && итог.часы.every((м) => м === 8 * 60),
      `минуты от полуночи: ${JSON.stringify(итог.часы)}`,
    )
    check(
      'идентификаторы соседних суток не совпадают',
      Array.isArray(итог.идентификаторы) &&
        new Set(итог.идентификаторы).size === итог.идентификаторы.length,
      JSON.stringify(итог.идентификаторы),
    )
  }


  // Имя человека в уведомлении: появляется только когда людей больше одного.
  const конкор = { id: 'm1', name: 'Конкор', dose: '5 мг', times: ['08:00'], perTime: 1 }
  check('у одного человека имени в строке нет', doseLine(конкор) === 'Конкор 5 мг')
  check('у двоих имя впереди', doseLine(конкор, 'Жена') === 'Жена: Конкор 5 мг')
  check('пустое имя не подставляется', doseLine(конкор, null) === 'Конкор 5 мг')

  // Потолок идентификатора. Граница, за которой начинаются отложенные
  // напоминания, обязана лежать выше него — иначе обычные напоминания начнут
  // выдавать себя за отложенные и перестанут сниматься. Прежняя граница в
  // 900 000 этот потолок не покрывала, и через год с небольшим уборка
  // замолчала бы.
  const потолок = (2047 * 8 + 7) * 1024 + 127 * 8 + 7
  let максимум = 0
  for (const день of [0, 1, 1000, 2047, 2048, 4095]) {
    for (const приём of [0, 5, 127]) {
      for (const шаг of [0, 3, 7]) {
        // День передаётся меткой времени, поэтому считаем от эпохи по суткам.
        const id = reminderId(день * 24 * 3600_000, приём, шаг, 7)
        максимум = Math.max(максимум, id)
      }
    }
  }
  check('идентификатор не выходит за расчётный потолок', максимум <= потолок, `${максимум} > ${потолок}`)

  // ── по людям ─────────────────────────────────────────────────────────────
  // Одно уведомление на 08:00 на всех отмечало приём каждому, у кого таблетка на
  // это время. Теперь каждому — своё, с именем в заголовке.
  const пл_утро = new Date(2026, 8, 1, 6, 0, 0).getTime()
  const пл_семья = [
    { id: 'a', name: 'Метформин', dose: '850 мг', times: ['08:00'], perTime: 1, owner: 'p-dad' },
    { id: 'b', name: 'Конкор', dose: '5 мг', times: ['08:00'], perTime: 1, owner: 'p1' },
  ]
  const пл_кто = (m) => m.person
  const пл_имя = (id) => (id === 'p-dad' ? 'Отец' : 'Я')
  const пл_набор = buildReminders(пл_семья, пл_утро, { repeat: false, horizonDays: 1, personOf: пл_кто, personName: пл_имя })
  check('по уведомлению на человека', пл_набор.length === 2, `${пл_набор.length}`)
  check('заголовки называют людей', пл_набор.some((r) => r.title.startsWith('Отец · ')) && пл_набор.some((r) => r.title.startsWith('Я · ')))
  check('идентификаторы не сталкиваются', new Set(пл_набор.map((r) => r.id)).size === 2)
  check('у каждого — только свои таблетки', пл_набор.every((r) => (r.person === 'p-dad' ? r.body === 'Метформин' : r.body === 'Конкор')))
  check('в теле нет имени — оно в заголовке', пл_набор.every((r) => !r.body.includes(':')))

  const пл_один = buildReminders(пл_семья, пл_утро, { repeat: false, horizonDays: 1 })
  check('без людей — одно уведомление, как раньше', пл_один.length === 1 && !пл_один[0].person && пл_один[0].body.includes(' и '))

  // Горизонт укорачивается, чтобы не упереться в потолок системы.
  const пл_четверо = ['p1', 'p2', 'p3', 'p4'].flatMap((p) =>
    ['08:00', '13:00', '19:00', '22:00'].map((t, i) => ({ id: `${p}-${i}`, name: 'X', times: [t], perTime: 1, owner: p })),
  )
  const пл_много = buildReminders(пл_четверо, пл_утро, { repeat: true, personOf: пл_кто, personName: () => 'Кто-то' })
  check('пл_четверо с повторами не превышают потолок', пл_много.length <= MAX_REMINDERS, `${пл_много.length}`)
  // Потолок Android — 500 будильников на приложение, и на пятьсот первом он
  // роняет приложение, а не отбрасывает лишний. Значит наш потолок обязан
  // оставлять место отложенным и пробному.
  check('потолок с запасом до системных пятисот', MAX_REMINDERS <= 450, `${MAX_REMINDERS}`)
  const пл_дней = new Set(пл_много.map((r) => r.day)).size
  check('горизонт укоротился, но не короче трёх пл_дней', пл_дней >= 3 && пл_дней < 14, `пл_дней: ${пл_дней}`)

  // Сквозная проводка «Принял» из уведомления: кого отмечать.
  const шкаф = [
    { id: 'd', name: 'Метформин', times: ['08:00'], perTime: 1, owner: 'p-dad' },
    { id: 's', name: 'Конкор', times: ['08:00'], perTime: 1, owner: 'p1' },
    { id: 'x', name: 'Вечернее', times: ['20:00'], perTime: 1, owner: 'p-dad' },
  ]
  const людиШкафа = [{ id: 'p1', name: 'Я' }, { id: 'p-dad', name: 'Отец' }]
  const деньШкафа = new Date(2026, 8, 1, 0, 0, 0).getTime()
  const сейчасШкаф = деньШкафа + 8 * 3600_000 + 5 * 60_000
  const отцу = medicinesForReminder(шкаф, людиШкафа, '08:00', деньШкафа, сейчасШкаф, 'p-dad').map((m) => m.boxId)
  check('«Принял» отца отмечает только его таблетку на это время', отцу.join() === 'd', отцу.join())
  const всем = medicinesForReminder(шкаф, людиШкафа, '08:00', деньШкафа, сейчасШкаф).map((m) => m.boxId)
  check('без человека — всем на это время, как в одиночном дневнике', всем.join() === 'd,s', всем.join())
  // Список людей больше не нужен: человек записан в самом курсе, и пустым он
  // не бывает. Раньше на холодном старте приходилось гадать по коробке.
  const холодно = medicinesForReminder(шкаф, [], '08:00', деньШкафа, сейчасШкаф, 'p-dad').map((m) => m.boxId)
  check('людей читать не нужно — человек в самом курсе', холодно.join() === 'd', холодно.join())

  // Горизонт считается по временам каждого человека, а не по всем на всех.
  const разные = [
    { id: 'r1', name: 'A', times: ['08:00', '13:00', '19:00'], perTime: 1, owner: 'p-dad' },
    { id: 'r2', name: 'B', times: ['22:00'], perTime: 1, owner: 'p1' },
  ]
  const набор2 = buildReminders(разные, пл_утро, { repeat: true, personOf: пл_кто, personName: пл_имя })
  const дней2 = new Set(набор2.map((r) => r.day)).size
  check('два человека с разными часами держат полный горизонт', дней2 === 14, `дней: ${дней2}`)


  // Разряд человека в номере напоминания: людей в дневнике не больше, чем
  // различает номер, и внутри предела номера не совпадают.
  const пл_день = Date.UTC(2026, 8, 2)
  const пл_номера = new Set(Array.from({ length: MAX_PEOPLE }, (_, i) => reminderId(пл_день, 3, 2, i)))
  check('предел людей вмещается в разряд номера', MAX_PEOPLE <= 8)
  check('внутри предела номера людей не совпадают', пл_номера.size === MAX_PEOPLE)
  check('за пределом номер повторяется — потому предел и нужен', reminderId(пл_день, 3, 2, MAX_PEOPLE) === reminderId(пл_день, 3, 2, 0))

  // ── что отмечать руками ──────────────────────────────────────────────────
  const мк_день = Date.UTC(2026, 8, 5)
  const мк_авто = { id: 'a', name: 'Витамин D3', times: ['08:00'], perTime: 1, left: 30, perDay: 1, autoDeduct: true }
  const мк_руками = { id: 'b', name: 'Метформин', times: ['08:00'], perTime: 1, left: 30, perDay: 1 }
  const мк_только = buildReminders([мк_авто], мк_день - 3600_000, { repeat: false, horizonDays: 1 })
  check('приём из одного автосписываемого отмечать нечем', мк_только.every((r) => r.markable === false))
  const мк_оба = buildReminders([мк_авто, мк_руками], мк_день - 3600_000, { repeat: false, horizonDays: 1 })
  check('приём, где есть ручной препарат, отмечается', мк_оба.every((r) => r.markable === true))

  // ── подписи к системному экрану звука ────────────────────────────────────
  //
  // Кнопка громкости отправляла системное намерение вслепую и считала успехом
  // то, что `startActivity` не бросил исключение. На прошивках, где экрана
  // канала нет, человек попадал в общие настройки и искал громкость там, где
  // её не показывают, — а приложение молчало. Теперь оно знает, куда он попал,
  // и говорит это словами.
  const зв_экраны = ['channel', 'app-notifications', 'app-details', 'none']
  for (const экран of зв_экраны) {
    const подсказка = soundScreenHint(экран)
    check(`«${экран}»: подсказка есть`, !!подсказка && !!подсказка.title && !!подсказка.body)
    // Слов «канал уведомлений» не знает ни один человек, кроме разработчика
    // Android. Если они всплывут в подписи, её увидит семидесятипятилетний.
    check(`«${экран}»: без слова «канал»`, !/канал/i.test(подсказка.title + ' ' + подсказка.body), подсказка.title)
  }
  const зв_все = зв_экраны.map((э) => soundScreenHint(э).title)
  check('подсказки не повторяются', new Set(зв_все).size === зв_экраны.length)
  // «none» — единственный случай, где надо объяснить путь руками: экрана нет
  // вовсе, и вести человека некуда.
  check('у «none» есть путь руками', /Настройки телефона/.test(soundScreenHint('none').body))
  // Ни одна подсказка не обещает ползунок громкости на системном экране.
  // Проверено на Mate 60 Pro: EMUI открывает свой экран «Общение», где есть
  // мелодия и баннеры, а громкости нет. Обещать её — отправлять человека
  // искать то, чего на его телефоне нет.
  check('ни одна подсказка не обещает ползунок громкости',
    зв_экраны.every((э) => !/громкость\s*—\s*ползунк|ползунком/i.test(soundScreenHint(э).body)))

  return failures
}
